"""Проверить вето на разрез разворота: сколько раз сработало и справедливо ли.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ.  Первая редакция вето в `djvu.py` объявляла
«порог 0.5% ловит 84% контрольных при отказе на 1–2% настоящих корешков» —
и скрипт, которым это считали, в дерево не попал.  Через день утверждение
стало непроверяемым, а прогон по живой книге дал другое: 11 отказов из 189
(5.8%), и все одиннадцать ложные.  Замер без способа его повторить — это
мнение, набранное моноширинным шрифтом.

ЧТО МЕРИТ.  По каждому развороту: сработало ли вето, и если да — из-за чего.
Чернота, идущая через корешок, делится на два разряда, и это различение и
есть суть:

    сквозные  — чёрный прогон тянется через четверть ширины разворота и
                дальше.  Так выглядит линейка таблицы, пересекающей корешок:
                она идёт через обе страницы.  Вето по ним и должно срабатывать.
    короткие  — прогон в десяток-другой пикселей.  Так выглядит ТЕНЬ
                ПЕРЕПЛЁТА: у сканов разворота верхние строки корешка чернее
                всего.  Вето по ним — ложная тревога, и притом обидная: тень
                переплёта есть улика корешка, то есть прямо противоположна
                тому, что вето ищет.

Обе величины печатаются отдельно.  Ноль сквозных при ненулевых коротких и
ноль сквозных на чистом развороте — разные ответы, и сводить их в одно число
значит терять ровно тот разряд ошибки, ради которого промер и написан.

ЗАПУСК:

    python tools/промер-разворотов.py --самопроверка      # без книг, секунды
    python tools/промер-разворотов.py raw/*.djvu
    python tools/промер-разворотов.py --листы 17,20,23 raw/книга.djvu

Второй вид — посмотреть поимённо, что именно нашлось на подозрительных
листах.  Ими и проверяется, что признак различает: подставьте лист с
таблицей во весь разворот и лист с одной тенью переплёта — разряды должны
выйти разные.  Если оба попадают в «сквозные», признак не работает, и узнать
об этом надо здесь, а не из испорченной книги.

ЧЕГО ПРОМЕР НЕ ПРОВЕРЯЕТ, И ЭТО НАДО ЗНАТЬ.  Отрицательная сторона измерена
на живой книге: 11 бывших ложных вето сняты.  Положительная — что настоящая
линейка через корешок вето ВЫЗЫВАЕТ — на живых сканах не проверена: такого
разворота в трёх наших книгах не нашлось размеченным.  Проверена она пока
только синтетикой.  Значит цена ошибки прежняя и несимметричная: лишний
отказ отдаёт распознавателю двухколоночный разворот, страницы целы; разрез
по таблице уничтожает числа безвозвратно.
"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))
from booksmith import djvu  # noqa: E402


def развернуть(src, tmp):
    """djvu -> pdf во временный каталог, минуя проверку свежести в to_pdf."""
    out = os.path.join(tmp, "проба.pdf")
    subprocess.run([djvu._tool("ddjvu"), "-format=pdf", "-quality=85",
                    src, out], check=True, capture_output=True)
    return out


def столбец_реза(pix):
    """Тот же выбор столбца, что делает `_gutter`, — чтобы мерить то самое."""
    data = pix.samples
    lo = int(pix.width * (0.5 - djvu.GUTTER_BAND / 2))
    hi = int(pix.width * (0.5 + djvu.GUTTER_BAND / 2))
    best, best_ink = None, None
    for x in range(lo, max(hi, lo + 1)):
        ink = sum(255 - data[y * pix.stride + x] for y in range(pix.height))
        if best_ink is None or ink < best_ink:
            best, best_ink = x, ink
    return best


def промер(src, только=None):
    import pymupdf
    with tempfile.TemporaryDirectory() as tmp:
        doc = pymupdf.open(развернуть(src, tmp))
        альбомных = вето = 0
        сквозных_всего = коротких_всего = 0
        подробно = []
        for page in doc:
            r = page.rect
            if r.width <= r.height * djvu.MIN_SPREAD_RATIO:
                continue
            лист = page.number + 1
            if только and лист not in только:
                continue
            альбомных += 1
            pix = page.get_pixmap(dpi=djvu.PROBE_DPI,
                                  colorspace=pymupdf.csGRAY, clip=r)
            if pix.width < 8:
                continue
            x = столбец_реза(pix)
            сквозные, короткие = djvu.dark_rows(pix, x)
            сквозных_всего += len(сквозные)
            коротких_всего += len(короткие)
            доля = len(сквозные) / max(1, pix.height)
            если_вето = доля > djvu.RULE_MAX
            вето += если_вето
            if если_вето or только:
                подробно.append((лист, pix.height, сквозные, короткие, доля,
                                 если_вето))
        doc.close()
    return альбомных, вето, сквозных_всего, коротких_всего, подробно


СЛУЧАИ = (
    # (имя, что нарисовать поверх двух колонок текста, ждём ли вето)
    ("чистый корешок", None, False),
    ("тень переплёта сверху", "тень-верх", False),
    ("тень переплёта на всю высоту", "тень-вся", False),
    ("линейка через весь разворот", "линейка-вся", True),
    ("линейка через треть", "линейка-треть", True),
    ("таблица во весь разворот", "таблица", True),
    # Сканы серые, а не чёрные: без этого случая порог черноты `RULE_INK`
    # можно задрать до 250 — и ни один нарисованный чистым чёрным случай
    # этого не заметит. Мутация должна ловиться, иначе порог не проверен.
    ("выцветшая линейка через разворот", "линейка-серая", True),
    # Бумага у сканов не белая, а желтоватая. Без этого случая порог черноты
    # можно опустить до пяти — и всё поле листа станет «чернилами», а ни один
    # случай на белом фоне этого не заметит.
    ("жёлтая бумага, чистый корешок", "бумага-серая", False),
)


def самопроверка():
    """Умеет ли вето провалиться — на нарисованных листах, без книг.

    Половина случаев обязана вето вызвать, половина обязана не вызвать.
    Признак, который нельзя провалить, — не прибор: `≠` в прежнем разборе
    стояла у 416 таблиц из 448 и не значила ничего именно потому, что её
    никто не проверял против известной порчи.

    Возврат 1 при любом расхождении: проверка нужна такая, чтобы могла
    кого-нибудь остановить.

    ЧТО ЭТА ПРОВЕРКА ЛОВИТ.  Прогон с нарочно сдвинутой ручкой (мутация):

        RULE_RUN 0.25 -> 0.9     4 расхождения из 8
        RULE_RUN 0.25 -> 0.05    1
        RULE_MAX 0.005 -> 0.9    4
        RULE_INK 96 -> 250       1
        RULE_INK 96 -> 5         1
        RULE_BAND 0.012 -> 0.4   1
        GUTTER_BAND 0.20 -> 0.9  4
        MIN_SPREAD_RATIO 1.15 -> 9   0 — НЕ ловится

    Последняя не ловится честно: самопроверка зовёт `_gutter` напрямую и
    признака разворота не касается вовсе. Это область другой проверки, и
    молчать об этом нельзя — непроверенное, выданное за проверенное, и есть
    тот фон, ради ухода от которого всё написано.
    """
    import pymupdf

    def лист(вид):
        doc = pymupdf.open()
        pg = doc.new_page(width=800, height=500)
        if вид == "бумага-серая":
            pg.draw_rect(pg.rect, color=None, fill=(0.88, 0.85, 0.78))
        for x0 in (60, 430):                      # две колонки «текста»
            for i in range(20):
                pg.draw_line(pymupdf.Point(x0, 60 + i * 20),
                             pymupdf.Point(x0 + 310, 60 + i * 20),
                             color=(0, 0, 0), width=3)
        ч = (0, 0, 0)
        if вид == "тень-верх":
            # ШИРЕ полосы поиска (400 ± 40 pt), иначе `argmin` просто уйдёт
            # от тени в соседний чистый столбец, случай пройдёт по неверной
            # причине и мутацию порога не поймает. В книге тень именно такая:
            # накрывает весь корешок, и уйти от неё некуда.
            pg.draw_rect(pymupdf.Rect(340, 0, 460, 12), color=None, fill=ч)
        elif вид == "тень-вся":
            pg.draw_rect(pymupdf.Rect(396, 0, 404, 500), color=None, fill=ч)
        elif вид == "линейка-вся":
            pg.draw_line(pymupdf.Point(60, 250), pymupdf.Point(740, 250),
                         color=ч, width=4)
        elif вид == "линейка-треть":
            pg.draw_line(pymupdf.Point(270, 250), pymupdf.Point(530, 250),
                         color=ч, width=4)
        elif вид == "линейка-серая":
            g = (0.55, 0.55, 0.55)      # чернил ~115 из 255
            pg.draw_line(pymupdf.Point(60, 250), pymupdf.Point(740, 250),
                         color=g, width=5)
        elif вид == "таблица":
            for i in range(8):
                pg.draw_line(pymupdf.Point(60, 100 + i * 40),
                             pymupdf.Point(740, 100 + i * 40),
                             color=ч, width=4)
        return doc

    плохо = 0
    print("самопроверка вето:")
    for имя, вид, ждём in СЛУЧАИ:
        doc = лист(вид)
        pg = doc[0]
        вышло = djvu._gutter(pg, pg.rect) is None
        doc.close()
        сошлось = вышло == ждём
        плохо += not сошлось
        print(f"  {имя:32s} вето {'ДА ' if вышло else 'нет'}  "
              f"ждали {'ДА ' if ждём else 'нет'}"
              f"{'' if сошлось else '   <-- НЕ СОШЛОСЬ'}")
    print(f"  расхождений {плохо} из {len(СЛУЧАИ)}")
    return 1 if плохо else 0


def main(argv):
    только = None
    files = []
    i = 0
    while i < len(argv):
        if argv[i] == "--самопроверка":
            i += 1
        elif argv[i] == "--листы":
            только = {int(x) for x in argv[i + 1].split(",")}
            i += 2
        else:
            files.append(argv[i])
            i += 1
    if "--самопроверка" in argv:
        return самопроверка()
    if not files:
        print(__doc__)
        return 2

    for src in files:
        имя = os.path.basename(src)
        альб, вето, сквозных, коротких, подр = промер(src, только)
        print(f"\n{имя}")
        print(f"  альбомных листов {альб}, вето {вето} "
              f"({вето / max(1, альб):.1%})")
        print(f"  строк черноты через корешок: сквозных {сквозных}, коротких {коротких}")
        if коротких and not сквозных:
            print("  — вся чернота оказалась короткой: без различения "
                  "вето сработало бы напрасно на каждом таком листе")
        for лист, h, с, к, доля, v in подр[:20]:
            print(f"    лист {лист}: проба {h} строк, сквозные {с}, короткие {к}, "
                  f"доля сквозных {доля:.4f}{'  ВЕТО' if v else ''}")
        if len(подр) > 20:
            print(f"    … ещё {len(подр) - 20}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
