# -*- coding: utf-8 -*-
"""Граничные случаи починки <mark> и висячих скобок. Запуск: python3 test_marks.py"""
import re, sys, os
sys.path.insert(0, os.path.expanduser("~/booksmith-work/e1/src2"))
from booksmith.convert import _fix_marks as _fm, _close_commands, _unbrace, _plain_math

M = '<mark title="модель не уверена">'
ok = bad = 0

def _fix_marks(x): return _fm(x)[0]

def t(name, got, exp):
    global ok, bad
    if got == exp:
        ok += 1
    else:
        bad += 1
        print(f"ПРОВАЛ {name}\n  получили {got!r}\n  ждали    {exp!r}")

# --- (а) закрывающий тег съеден слэшем -----------------------------------
t("а: один слэш перед </mark>",
  _fix_marks(f"реакция{M} $\\</mark>Phi(x)$"),
  f"реакция{M} $</mark>\\Phi(x)$")
# --- ЧЁТНОСТЬ: `\\` это правильный текст, трогать нельзя ------------------
t("чётность: два слэша перед </mark> не трогаем",
  _fix_marks(f"строка{M}текст\\\\</mark> дальше"),
  f"строка{M}текст\\\\</mark> дальше")
t("чётность: три слэша — снимаем только непарный",
  _fix_marks(f"{M}текст\\\\\\</mark>Phi"),
  f"{M}текст\\\\</mark>\\Phi")
t("чётность: четыре слэша не трогаем",
  _fix_marks(f"{M}текст\\\\\\\\</mark>дальше"),
  f"{M}текст\\\\\\\\</mark>дальше")
# --- (б) открывающий тег съеден слэшем ------------------------------------
t("б: слэш перед <mark>",
  _fix_marks(f"$t_{{\\{M}lambda</mark>}}$"),
  f"$t_{{{M}\\lambda</mark>}}$")
t("б: чётная серия перед <mark> не трогаем",
  _fix_marks(f"конец строки\\\\{M}тут</mark>"),
  f"конец строки\\\\{M}тут</mark>")
# --- (в) спан через границу абзаца ----------------------------------------
t("в: пометка через пустую строку — закрыть и открыть заново",
  _fix_marks(f"первый {M}кусок\n\nвторой кусок</mark> хвост"),
  f"первый {M}кусок</mark>\n\n{M}второй кусок</mark> хвост")
t("в: пометка через ДВЕ границы",
  _fix_marks(f"{M}а\n\nб\n\nв</mark>"),
  f"{M}а</mark>\n\n{M}б</mark>\n\n{M}в</mark>")
# --- незакрытая пометка в конце абзаца ------------------------------------
t("незакрытая пометка закрывается на границе абзаца",
  _fix_marks(f"{M}висит\n\nследующий"),
  f"{M}висит</mark>\n\n{M}следующий</mark>")
# --- лишний закрывающий без пары ------------------------------------------
t("лишний </mark> выбрасывается",
  _fix_marks("текст</mark> дальше"),
  "текст дальше")
# --- ничего не трогаем там, где всё хорошо --------------------------------
CLEAN = f"обычный {M}помеченный</mark> текст\n\nи ещё {M}один</mark>."
t("здоровый текст неизменен", _fix_marks(CLEAN), CLEAN)
t("идемпотентность", _fix_marks(_fix_marks(CLEAN)), CLEAN)
BROKEN = f"{M} $\\</mark>Phi\n\n{M}а\n\nб</mark>"
t("идемпотентность на битом", _fix_marks(_fix_marks(BROKEN)), _fix_marks(BROKEN))
# --- атрибут с кавычками и угловой скобкой (Э3 кладёт варианты свидетелей) -
E3 = '<mark title="чтения разошлись: 1,5, 15">'
t("тег с запятыми в title", _fix_marks(f"а\\{E3}бета</mark>"),
  f"а{E3}\\бета</mark>")

# --- скобки ----------------------------------------------------------------
t("незакрытая \\cmd{ закрывается в конце абзаца",
  _close_commands("текст \\mathrm{Fe и дальше\n\nдругой абзац"),
  ("текст \\mathrm{Fe и дальше}\n\nдругой абзац", 1))
t("закрытая не трогается",
  _close_commands("текст \\mathrm{Fe} тут"), ("текст \\mathrm{Fe} тут", 0))
t("одинокая { в прозе без команды не трогается",
  _close_commands("см. пункт {3 и далее"), ("см. пункт {3 и далее", 0))
t("лишняя } безобидна",
  _close_commands("\\mathrm{Fe}} хвост"), ("\\mathrm{Fe}} хвост", 0))
t("закрытая скобка + перевод даёт читаемый текст",
  _plain_math(_close_commands("$\\mathrm{Fe}$")[0]), "Fe")

# --- _unbrace --------------------------------------------------------------
t("парная обёртка снимается", _unbrace(" {abc} "), "abc")
t("непарные не снимаются", _unbrace("{a} + {b}"), "{a} + {b}")
t("команда не калечится", _unbrace("\\mathrm{Fe}"), "\\mathrm{Fe}")
t("вложенная обёртка", _unbrace("{{x}}"), "x")
t("пустая ячейка", _unbrace("  "), "")
t("старое поведение было бы \\mathrm{Fe", "\\mathrm{Fe}".strip(" {}"), "\\mathrm{Fe")

print(f"\nпройдено {ok}, провалено {bad}")
sys.exit(1 if bad else 0)
