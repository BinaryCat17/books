# -*- coding: utf-8 -*-
"""Каждая пометка должна быть померена против каждой порчи.

Пометка, ни разу не поставленная против нарочной порчи, — обещание, а не
прибор.  Таких в отчёте книги стояло две: `≠` и `⚠` печатались числами, и ни
у одной не было сказано, что это число значит.

Проверка работает на ПОДСТАВКЕ — трёх выдуманных таблицах с известными
ответами, — а не на книге: на книге медленно, и ответ там неизвестен.
Отдельно проверяется главное свойство, ради которого всё делалось:

  * замена цифры и обрезка хвоста МЕНЯЮТ число пометок в книге;
  * циклический сдвиг строки НЕ МЕНЯЕТ его ни на одну — по построению
    `merge.mark_cells`, который сличает мешок значений, а не их места.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.environ.get("BOOKSMITH_SRC") or os.path.join(HERE, "..", "src")
sys.path.insert(0, os.path.abspath(SRC))


def таблица(строки):
    out = ["<table>"]
    for r in строки:
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    out.append("</table>")
    return "\n".join(out)


# Подставка: одна таблица, десять строк, два столбца. Основа и два свидетеля
# читают её одинаково — значит на чистой книге ни одной пометки `≠` быть не
# должно, и фон равен нулю.  Это делает ответ однозначным.
# Метки строк — БЕЗ цифр нарочно: иначе порча «замена цифры» бьёт и по ним,
# а `строка 3` -> `строка 8` создаёт двойника уже существующего значения, и
# пометка садится на невиновную ячейку (см. отдельную проверку ниже).
БУКВЫ = ("альфа", "бета", "гамма", "дельта", "эпсилон",
         "дзета", "эта", "тета", "йота", "каппа")
СТРОКИ = [[f"строка {б}", f"{100 + i * 7}"] for i, б in enumerate(БУКВЫ)]
ОСНОВА = "Перед таблицей.\n\n" + таблица(СТРОКИ) + "\n\nПосле таблицы.\n"
СВИДЕТЕЛИ = [ОСНОВА, ОСНОВА]


def main():
    from booksmith import calibrate as K

    беды = []
    print(f"пометок в реестре MARKS: {len(K.MARKS)}; "
          f"порч в реестре SPOILERS: {len(K.SPOILERS)}; "
          f"пар к замеру: {len(K.MARKS) * len(K.SPOILERS)}")

    # 1. Реестры непусты и без повторов имён.
    for имя, реестр in (("MARKS", K.MARKS), ("SPOILERS", K.SPOILERS)):
        имена = [x[0] for x in реестр]
        if len(set(имена)) != len(имена):
            беды.append(f"{имя}: повторяющиеся имена {имена}")
        if not имена:
            беды.append(f"{имя} пуст")
        for x in реестр:
            if len(x) != 3 or not callable(x[1]) or not x[2]:
                беды.append(f"{имя}: у записи {x[0]!r} нет описания или тела")

    целый = K.разобрать(ОСНОВА)
    все = K.адреса(целый)
    print(f"подставка: ячеек {len(все)}, чистый фон `≠` "
          f"{len(K.пометка_ne(ОСНОВА, СВИДЕТЕЛИ)) / len(все):.0%}")
    if K.пометка_ne(ОСНОВА, СВИДЕТЕЛИ):
        беды.append("на подставке, где все чтения совпали, `≠` всё равно стоит")

    # 2. Собрать поимённую матрицу: каждая пометка × каждая порча.
    import random
    матрица = {}
    print(f"\n{'порча':20s} {'пометка':8s} {'испорчено':>10s} "
          f"{'помечено':>9s} {'пометок в книге':>17s}")
    for имя_порчи, порча, _ in K.SPOILERS:
        rnd = random.Random("подставка:" + имя_порчи)
        d = K.копия(целый)
        испорчено = порча(d, sorted(все), rnd)
        порченый = K.собрать(d)
        # Порча не имеет права ломать разметку: собранный обратно текст
        # обязан остаться таблицей с тем же числом ячеек.
        if len(K.адреса(K.разобрать(порченый))) != len(все):
            беды.append(f"{имя_порчи}: после порчи ячеек стало "
                        f"{len(K.адреса(K.разобрать(порченый)))} вместо {len(все)}")
        for имя_метки, метка, _ in K.MARKS:
            до = метка(ОСНОВА, СВИДЕТЕЛИ)
            после = метка(порченый, СВИДЕТЕЛИ)
            матрица[(имя_метки, имя_порчи)] = {
                "испорчено": len(испорчено),
                "помечено на порченых": len(после & испорчено),
                "пометок до": len(до), "пометок после": len(после),
            }
            v = матрица[(имя_метки, имя_порчи)]
            print(f"{имя_порчи:20s} {имя_метки:8s} {v['испорчено']:10d} "
                  f"{v['помечено на порченых']:9d} "
                  f"{v['пометок до']:8d} -> {v['пометок после']:<6d}")

    # 3. Ни одной незамеренной пары.
    пропущено = [(m, s) for m, _f, _d in K.MARKS for s, _g, _e in K.SPOILERS
                 if (m, s) not in матрица]
    if пропущено:
        беды.append(f"не замерено пар: {пропущено}")

    # 4. Ответы, известные заранее.
    ожидания = [
        ("≠", "замена цифры", "должна ловиться почти вся", lambda v:
         v["помечено на порченых"] >= 0.8 * v["испорчено"]),
        ("≠", "оторванный хвост", "должна ловиться почти вся", lambda v:
         v["помечено на порченых"] >= 0.8 * v["испорчено"]),
        ("≠", "сдвиг строки", "число пометок в книге не меняется НИ НА ОДНУ",
         lambda v: v["пометок до"] == v["пометок после"]),
        ("⚠", "сдвиг строки", "статическая пометка не реагирует",
         lambda v: v["пометок до"] == v["пометок после"]),
    ]
    print()
    for имя_метки, имя_порчи, что, годно in ожидания:
        v = матрица[(имя_метки, имя_порчи)]
        ok = годно(v)
        print(f"  {'ок  ' if ok else 'МИМО'}  {имя_метки} против «{имя_порчи}»: {что}")
        if not ok:
            беды.append(f"{имя_метки}/{имя_порчи}: {что} — не выполнено: {v}")

    # 5. Отдельно — свойство, из-за которого «поймано» нельзя читать как
    # «найдено».  Если порча превратила значение в ДВОЙНИКА уже стоящего в
    # книге, пометка садится на первую попавшуюся из двух одинаковых ячеек, и
    # с равной вероятностью это невиновная.  Знать это надо: очередь на
    # сверку, построенная по `≠`, будет посылать человека не туда.
    двойники = таблица([["метка", "12"], ["метка", "34"], ["метка", "56"]])
    основа2 = двойники
    свид2 = [таблица([["метка", "12"], ["метка", "34"], ["метка", "56"]])] * 2
    d = K.разобрать(основа2)
    адр = K.адреса(d)
    # Портим `34` в `12` — теперь `12` в книге дважды, а у свидетелей один раз.
    цель = sorted(адр)[3]
    K.взять(d, цель)[1] = "12"
    после = K.пометка_ne(K.собрать(d), свид2)
    на_виновной = цель in после
    print(f"\n  двойник: испортили одну ячейку в `12`; помеченных ячеек "
          f"{len(после)}, из них виновная — {'да' if на_виновной else 'НЕТ'}")
    # НАЗВАННАЯ СЛЕПАЯ ЗОНА, а не провал. Спор закрыт замером против ручной
    # разметки (29 дефектов, шесть собранных книг):
    #
    #     множество (нынешнее)   пометок  6 714   найдено 14 из 29   лифт 2.70
    #     мультимножество        пометок 11 411   найдено 17 из 29   лифт 1.93
    #
    # Лишние 4 697 пометок покупают три дефекта — 0.064% на пометку против
    # 0.21% у уже стоящих. Возврат к кратности сделал бы прибор тупее, а не
    # зорче, поэтому слепая зона принята сознательно. Население под риском —
    # 23 516 непустых ячеек из 37 611 (62.5%): это те, у кого в своей книге
    # есть значение-двойник. Население, а не вред.
    #
    # Проверка обязана про это ГОВОРИТЬ и не обязана падать: падение звало бы
    # чинить то, что измерено и выбрано.
    if len(после) != 1:
        print(f"  (слепая зона: помечено {len(после)} ячеек вместо одной — "
              f"порча стала двойником уже стоящего значения; см. комментарий)")

    for x in беды:
        print("  !!", x)
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
