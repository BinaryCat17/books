"""Сговор двух копий разбора `--pages`: `detect` и `dots_ocr/entrypoint`.

ПОЧЕМУ КОПИЯ ВООБЩЕ ЕСТЬ, И ЭТО НЕ ЛЕНЬ. На арендованную машину уезжают
четыре файла (`inputs` в `models/dots_ocr/__init__.py:spec()`), пакета
`booksmith` там нет — значит разбор строки страниц обязан приехать своим
текстом. Свести копии в одну нельзя, не отправив туда весь пакет; сделать так,
чтобы они не расходились МОЛЧА, — можно, и это здесь.

ЧЕМ ОПЛАЧЕНО. Сторожа не было, и копия сама это признавала: «СТОРОЖА У ЭТИХ
ДВУХ КОПИЙ НЕТ… расхождение поймает только человек. Сверка ручная — обе
функции на входах «1», «1,4,7-9», «130», «2-4» обязаны дать одно и то же, а на
«0», «0-9», «3-1» отказать обе». Список ручной сверки был НЕПОЛОН: пробела в
нём нет, а разошлись копии именно на нём. Замер до починки — 4 расхождения из
13 входов:

    «1 3»      detect [0, 2]        dots ValueError: invalid literal for int()
    «1 4 7-9»  detect [0, 3, 6, 7, 8]  dots тот же ValueError
    «x»        detect отказ с образцом  dots тот же ValueError
    «7-x»      detect отказ с образцом  dots тот же ValueError

Цена расхождения — не косметическая: строка разбирается НА КАРТЕ, после того
как развёрнуты веса и пошли деньги, и голая трассировка там означает пустую
аренду. `books detect --pages "1 3"` дома работает, тот же ключ на боксе падал.

ЕДИНСТВЕННОЕ ЗАКОННОЕ РАСХОЖДЕНИЕ — дефис. У `dots` он значит «вся книга»,
и это соглашение ОБОЛОЧКИ, а не разбора: `run.sh` подставляет `${4:--}`, а
`spec()` шлёт `pages or '-'` — пустой позиционный аргумент до `bash` не
доезжает. У `detect` дефис отказ вслух, потому что там пустое значение
выражается пустым значением. Расхождение объявлено здесь и проверяется,
а не подразумевается.
"""
import importlib.util
import os
import sys

import support

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

# Входы, на которых копии обязаны совпадать ДО ЗНАКА. Пробел и мусор стоят
# здесь нарочно: список ручной сверки в докстроке копии их не называл, и
# расхождение прожило ровно в этой слепой зоне.
TABLE = ("1", "1,4,7-9", "2-4", "10", "0", "0-9", "3-1", "",
         "1 3", "1 4 7-9", "1, 4 ,7-9", "x", "7-x", "1,,3", "11")

# Дефис — соглашение оболочки, см. шапку. Проверяется отдельно и в обе стороны.
SHELL_ALL = "-"

TOTAL = 10


def _dots_parse_pages():
    """`parse_pages` из копии, что уезжает на карту. Грузим по пути.

    Импортом пакета не взять: `models/dots_ocr/entrypoint.py` — точка входа
    ДЛЯ БОКСА, она не часть импортируемого дерева и тянуть её как модуль
    пакета значило бы проверять не тот файл, который поедет.

    Путь спрашивается у `support`, а не собирается здесь из `__file__`, и это
    не стиль: батарея порчи (`sources()`) подменяет `support.SRC` копией
    дерева с одной испорченной строкой. Тест, знающий путь сам, читал бы
    настоящий файл мимо порчи и был бы зелёным на сломанном коде — так и
    вышло на первом прогоне: две мутации напечатали «НЕ ПОЙМАНА», хотя
    ручной откат обе проверки роняет.
    """
    path = support.src_path(os.path.join("models", "dots_ocr",
                                         "entrypoint.py"))
    spec = importlib.util.spec_from_file_location("dots_entrypoint", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.parse_pages


def _outcome(fn, value):
    """Что вышло: страницы, отказ вслух или НЕ отказ вслух.

    Три ответа, а не два. «Отказ вслух» (`SystemExit`) и «упало как попало»
    (любое другое исключение) — разные вещи: первое печатает образец и код
    возврата, второе даёт трассировку. Ровно этим копии и расходились, и
    свести их в один ответ значило бы не заметить починку.
    """
    try:
        return ("pages", fn(value, TOTAL))
    except SystemExit:
        return ("отказ вслух", None)
    except BaseException as e:                     # noqa: BLE001 — нам нужен вид
        return (f"упало как попало: {type(e).__name__}", None)


def test_both_copies_of_parse_pages_agree():
    """Две копии разбора `--pages` отвечают ОДИНАКОВО на общем списке.

    Сговор здесь между файлом, который считает дома, и файлом, который
    считает за деньги. Разойдясь, оба остаются исправными на вид: дома
    проверено, на карте падает.
    """
    from booksmith.detect import parse_pages as canon
    other = _dots_parse_pages()

    расхождения = []
    for value in TABLE:
        a, b = _outcome(canon, value), _outcome(other, value)
        if a != b:
            расхождения.append(f"  «{value}»: detect {a} != dots {b}")
    assert not расхождения, (
        "копии разбора `--pages` разошлись:\n" + "\n".join(расхождения)
        + "\nПравка в одной обязана повторяться в другой: "
          "`detect.parse_pages` и `models/dots_ocr/entrypoint.parse_pages`. "
          "Разбирается это на арендованной карте, где отказ стоит денег.")


def test_the_dash_means_the_whole_book_only_on_the_box():
    """Дефис — соглашение ОБОЛОЧКИ, и расходятся копии на нём НАРОЧНО.

    Проверяется в обе стороны, иначе «объявленное расхождение» неотличимо от
    незамеченного: у `dots` дефис обязан дать всю книгу, у `detect` — отказ
    вслух. Совпади они — значит кто-то свёл копии не думая, и `run.sh` с его
    `${4:--}` начнёт получать отказ там, где раньше считал всю книгу.
    """
    from booksmith.detect import parse_pages as canon
    other = _dots_parse_pages()

    assert _outcome(other, SHELL_ALL) == ("pages", list(range(TOTAL))), (
        "у копии для карты дефис перестал значить «вся книга». "
        "`run.sh` подставляет его как `${4:--}`, а `spec()` шлёт "
        "`pages or '-'` — пустого позиционного аргумента там нет")
    assert _outcome(canon, SHELL_ALL) == ("отказ вслух", None), (
        "`detect.parse_pages` принял дефис. Дома пустое значение выражается "
        "пустым значением, и дефис здесь — опечатка, о которой надо сказать")


def test_a_space_separates_pages_in_both_copies():
    """Пробел разделяет так же, как запятая — В ОБЕИХ копиях.

    Отдельной проверкой, а не строкой общей таблицы, потому что это и есть
    место, где копии прожили расхождение: список ручной сверки в докстроке
    копии пробела не называл, и `--pages "1 3"` на карте падал голым
    `ValueError` после того, как веса развёрнуты и пошли деньги.
    """
    from booksmith.detect import parse_pages as canon
    other = _dots_parse_pages()

    for fn, имя in ((canon, "detect"), (other, "dots_ocr")):
        assert _outcome(fn, "1 3") == ("pages", [0, 2]), (
            f"{имя}: «1 3» не понято как две страницы. Пробел обязан "
            f"разделять так же, как запятая")
        assert _outcome(fn, "x") == ("отказ вслух", None), (
            f"{имя}: мусор в `--pages` обязан быть отказом ВСЛУХ, с образцом "
            f"и кодом возврата, а не трассировкой")
