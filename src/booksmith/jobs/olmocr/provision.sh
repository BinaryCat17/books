#!/usr/bin/env bash
# Разворачивание окружения на арендованной машине — то, что раньше было
# слоями образа.
#
# Почему не слоями: docker качает три слоя одновременно и по одному потоку на
# слой, а реестр режет соединение до ~25 Мбит/с — итого 76 Мбит/с потолка
# независимо от канала машины.  uv и hf открывают десятки соединений и канал
# насыщают.  Здесь это важнее, чем у paddleocr: веса olmOCR-2 весят 16.6 ГБ
# против 2.2 ГБ у PaddleOCR-VL, и разница между 76 и 1100 Мбит/с — это
# двадцать девять минут против двух.
#
# Скрипт идемпотентен: на прогретой машине (--reuse) всё уже на месте, и он
# отрабатывает за секунды.  Каждый шаг печатает своё время — чтобы «старт
# долгий» всегда разбирался на конкретный шаг.
set -euo pipefail

ENVDIR=${ENVDIR:-/opt/env}
MODELS=${MODELS:-/models}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

# Веса берём в bf16, а не в FP8, хотя штатный для olmocr — именно FP8
# (allenai/olmOCR-2-7B-1025-FP8 стоит умолчанием в их pipeline.py).  Причины
# две.  Первая: FP8_DYNAMIC — это W8A8 с квантованием активаций на лету, и
# родные ядра для него есть только начиная с sm_89; на 3090 (sm_86) vLLM
# уходит на запасной путь или не стартует вовсе, а карту мы выбираем по
# рынку.  Вторая: PaddleOCR-VL мы считаем в bf16, и сравнивать качество надо
# в той же точности, иначе разница в таблицах окажется разницей в
# квантовании.  На 4090 FP8 включается одной переменной:
#   OLMOCR_MODEL_REPO=allenai/olmOCR-2-7B-1025-FP8
# и экономит 6.5 ГБ видеопамяти и столько же трафика.
MODEL_REPO=${OLMOCR_MODEL_REPO:-allenai/olmOCR-2-7B-1025}

export UV_LINK_MODE=copy
export UV_HTTP_TIMEOUT=180
export HF_HUB_DISABLE_PROGRESS_BARS=1

step() {
    local label="$1"; shift
    local t0 t1
    t0=$(date +%s)
    "$@"
    t1=$(date +%s)
    printf '== %-18s %4dс\n' "$label" "$((t1 - t0))"
}

step "python" uv python install 3.12
# --allow-existing обязателен: на прогретой машине (--reuse, или та же
# машина под тем же тегом) каталог уже есть, и uv без этого флага падает с
# "A virtual environment already exists at: /opt/env", то есть ровно на том
# сценарии, ради которого скрипт и писался идемпотентным.
step "окружение" uv venv "$ENVDIR" --python 3.12 --allow-existing

export VIRTUAL_ENV="$ENVDIR"
export PATH="$ENVDIR/bin:$PATH"

# Ставится constraints.txt — закреплённое дерево целиком, а не верхний
# уровень: иначе разрешение зависимостей идёт здесь, на арендованной карте,
# и новый релиз любой транзитивной зависимости роняет книгу на середине.
# requirements.in остаётся входом для пересборки этого файла, см. его шапку.
#
# --torch-backend=cu130 нужен и здесь: версия закреплена как 2.13.0+cu130,
# а такой на PyPI нет — она лежит в индексе pytorch.
step "колёса" uv pip install -r "$HERE/constraints.txt" --torch-backend=cu130

# Веса кладём в каталог, названный по репозиторию: при смене bf16 на FP8
# прогретая машина не должна отдать чужие 16.6 ГБ под именем новых 10.
step "веса olmOCR" hf download "$MODEL_REPO" \
    --local-dir "$MODELS/$(basename "$MODEL_REPO")"
