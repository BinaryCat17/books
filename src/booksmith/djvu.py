RULE_INK = 96               # насколько тёмен пиксель, чтобы счесть его чернотой
RULE_RUN = 0.25             # чернота через эту долю ширины разворота — линейка
                            # Порог стоит В ПРОПАСТИ, и это не «запас 2.3x».
