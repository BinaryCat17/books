"""`books calibrate` — нанести порчу нарочно и померить, метит ли её свод.

Зачем это вообще.  Отчёт печатает «ячеек помечено ≠: 7213 из 24 279» и на
этом останавливается.  Число красивое и ничего не значащее: оно говорит, где
чтения разошлись, и молчит о том, как часто расхождение означает ошибку.
Ручная сверка двадцати таблиц (Э8) померила это прямо и дала **ρ = −0.01**
между долей помеченных ячеек и ошибками в числах — то есть как прибор для
чисел свод показывает шум.

Калибровка — способ узнать то же самое без человека и без денег: испортить
ячейку известным образом и посмотреть, заметит ли пометка.  Три величины на
каждую пару «пометка × порча»:

    фон      доля помеченных среди НЕиспорченных ячеек
    поймано  доля помеченных среди испорченных
    лифт     поймано / фон

Лифт — единственное честное число из трёх.  «Поймано 25%» звучит как работа,
пока не выяснится, что фон тоже 25%: тогда пометка просто стоит на каждой
четвёртой ячейке и про порчу не знает ничего.  **Лифт ниже единицы означает,
что испорченная ячейка помечается РЕЖЕ средней** — прибор показывает в
обратную сторону.

Главный вывод замера, ради которого команда и написана: против **сдвига
строки** лифт 0.29–0.65 во всех шести книгах.  Механизм назван и проверяем:
`merge.mark_cells` сличает МЕШОК значений по всей книге (`seen[v]`,
`w[v] >= k`), а сдвиг строки мешок не меняет — те же значения, другие места.
Пометка слепа к нему по построению, а не по недосмотру.  Э8 говорит, что
сдвиг строки — ведущий вид незаметной порчи: 30 из 128 (23%), и все до одного
одинаковы во всех трёх проходах.

Реестры `MARKS` и `SPOILERS` заведены не для красоты: проверка
`test_marks_spoilers.py` требует, чтобы каждая пометка была померена против
каждой порчи.  Пометка, ни разу не поставленная против порчи, — это обещание,
а не прибор; таких в отчёте уже стояло две.
"""
import collections
import html
import os
import random
import re

from . import layout, merge

TABLE = re.compile(r"<table\b.*?</table>", re.I | re.S)
TR = re.compile(r"<tr\b[^>]*>.*?</tr>", re.I | re.S)
CELL = re.compile(r"(<t[dh][^>]*>)(.*?)(</t[dh]>)", re.I | re.S)
TAG = re.compile(r"<[^>]+>")


def чисто(c):
    """Значение ячейки без разметки и без пометок."""
    return html.unescape(TAG.sub("", c)).replace("⚠", "").replace("≠", "").strip()


# --------------------------------------------------------------- разбор книги
#
# Свой разбор, а не `merge.cells_of_text`: тому нужен счёт значений, а нам —
# АДРЕС каждой ячейки, чтобы после порчи узнать ту же самую.  Адрес —
# (номер таблицы, номер строки, номер ячейки в строке); он переживает и
# порчу, и пометку, потому что ни то, ни другое не меняет числа тегов.


def разобрать(text):
    """Книга -> [куски прозы и таблиц]. Обратно собирается `собрать`."""
    doc, prev = [], 0
    for t in TABLE.finditer(text):
        doc.append(("проза", text[prev:t.start()]))
        doc.append(("таблица", _разобрать_таблицу(t.group(0))))
        prev = t.end()
    doc.append(("проза", text[prev:]))
    return doc


def _разобрать_таблицу(s):
    швы, строки, last = [], [], 0
    for r in TR.finditer(s):
        швы.append(s[last:r.start()])
        строки.append(_разобрать_строку(r.group(0)))
        last = r.end()
    швы.append(s[last:])
    if not строки:
        # Таблица без `<tr>` — так бывает у вырожденных: ячейки лежат подряд.
        # Считаем её одной строкой, чтобы адресация не разъезжалась.
        швы, строки = ["", ""], [_разобрать_строку(s)]
        return {"швы": ["", ""], "строки": строки, "без строк": True}
    return {"швы": швы, "строки": строки, "без строк": False}


def _разобрать_строку(s):
    швы, ячейки, last = [], [], 0
    for m in CELL.finditer(s):
        швы.append(s[last:m.start()])
        ячейки.append([m.group(1), m.group(2), m.group(3)])
        last = m.end()
    швы.append(s[last:])
    return {"швы": швы, "ячейки": ячейки}


def _собрать_строку(r):
    out = []
    for i, шов in enumerate(r["швы"]):
        out.append(шов)
        if i < len(r["ячейки"]):
            out.append("".join(r["ячейки"][i]))
    return "".join(out)


def _собрать_таблицу(t):
    if t.get("без строк"):
        return _собрать_строку(t["строки"][0])
    out = []
    for i, шов in enumerate(t["швы"]):
        out.append(шов)
        if i < len(t["строки"]):
            out.append(_собрать_строку(t["строки"][i]))
    return "".join(out)


def собрать(doc):
    return "".join(x[1] if x[0] == "проза" else _собрать_таблицу(x[1])
                   for x in doc)


def адреса(doc):
    """Все непустые ячейки: адрес -> значение."""
    out = {}
    ti = 0
    for вид, тело in doc:
        if вид != "таблица":
            continue
        for ri, r in enumerate(тело["строки"]):
            for ci, c in enumerate(r["ячейки"]):
                v = чисто(c[1])
                if v:
                    out[(ti, ri, ci)] = v
        ti += 1
    return out


def взять(doc, адрес):
    ti, ri, ci = адрес
    к = [x[1] for x in doc if x[0] == "таблица"][ti]
    return к["строки"][ri]["ячейки"][ci]


def копия(doc):
    import copy
    return copy.deepcopy(doc)


# ------------------------------------------------------------------- порчи
#
# Три вида, и все три взяты из ручной разметки Э8, а не выдуманы: из 179
# дефектов двадцати таблиц 90 «стоит не то» (испорчено), 30 «цифры верны,
# строка чужая» (сдвиг), 51 «пусто» (оторвано/потеряно).


def подставить(c, новое):
    """Заменить содержимое ячейки, СОХРАНИВ уже стоящие в ней пометки.

    Без этого порча сама снимала бы `⚠`, и калибровка отвечала бы не на
    вопрос «замечает ли пометка порчу», а на вопрос «стирает ли порча
    пометку».  Первая редакция этого не делала, и лифт `⚠` против сдвига и
    обрезки выходил ровно 0.00 на всех шести книгах — красивое число,
    означающее только то, что мы сами затёрли знак.
    """
    хвост = "".join(m for m in ("⚠", "≠") if m in c[1])
    c[1] = новое + (" " + хвост if хвост else "")


def порча_цифра(doc, адреса_, rnd):
    """Заменить одну цифру другой. Значение остаётся правдоподобным.

    Самый лёгкий для пометки случай: мешок значений книги меняется, и
    свидетель, прочитавший ячейку иначе, обязан дать расхождение.  Если
    пометка не ловит даже этого, она не ловит ничего.
    """
    испорчено = set()
    for адрес in адреса_:
        c = взять(doc, адрес)
        v = c[1]
        # Только ASCII-цифры: `ch.isdigit()` в питоне истинно и для `₂`, и
        # для `②`, а заменять подстрочник в `Cr₂O₃` значит портить не число,
        # а формулу — это уже другая порча.
        цифры = [i for i, ch in enumerate(v) if ch in "0123456789"]
        if not цифры:
            continue
        i = rnd.choice(цифры)
        новая = str((int(v[i]) + 1 + rnd.randrange(8)) % 10)
        if новая == v[i]:
            новая = str((int(v[i]) + 3) % 10)
        c[1] = v[:i] + новая + v[i + 1:]
        испорчено.add(адрес)
    return испорчено


def порча_хвост(doc, адреса_, rnd):
    """Оторвать хвост значения — то, что в разметке Э8 названо «потеряно».

    Половина знаков с конца, но не меньше одного знака остаётся: пустая
    ячейка `mark_cells` вообще не метит и в знаменатель не входит
    (`merge.py:275` — выход до `total += 1`), и порча превратилась бы в
    исчезновение единицы измерения.
    """
    испорчено = set()
    for адрес in адреса_:
        c = взять(doc, адрес)
        v = чисто(c[1])
        if len(v) < 4:
            continue
        подставить(c, v[:max(1, len(v) // 2)])
        испорчено.add(адрес)
    return испорчено


def порча_сдвиг(doc, адреса_, rnd):
    """Сдвинуть столбец на строку вниз: цифры верны, строка чужая.

    Это ведущий вид незаметной порчи (Э8: 30 из 128, 23%) и единственный,
    против которого у нас сегодня нет ни одного канала: ни смена основы, ни
    голосование, ни третий проход его не берут — все три чтения сдвигают
    одинаково.

    Порча наносится СТОЛБЦУ целиком, а не ячейке: сдвинутая одиночная ячейка
    — это подмена значения, то есть другая порча.  Испорченными считаются
    только те ячейки, у которых значение действительно сменилось.
    """
    испорчено = set()
    таблицы = collections.defaultdict(set)
    for ti, ri, ci in адреса_:
        таблицы[ti].add(ci)
    все = [x[1] for x in doc if x[0] == "таблица"]
    предел = len(адреса_)
    for ti in sorted(таблицы):
        t = все[ti]
        for ci in sorted(таблицы[ti]):
            if len(испорчено) >= предел:
                break
            строки = [r for r in t["строки"] if len(r["ячейки"]) > ci]
            if len(строки) < 3:
                continue
            было = [чисто(r["ячейки"][ci][1]) for r in строки]
            # Сдвиг ЦИКЛИЧЕСКИЙ: последнее значение уходит наверх, ничего не
            # теряется и ничего не появляется.  Это важно.  Нецикличный сдвиг
            # (последнее значение выбрасывается, первое дублируется) меняет
            # мешок значений книги, и часть порчи ловится случайно — не
            # потому, что пометка видит сдвиг, а потому, что видит пропажу.
            # Мы меряем именно сдвиг: цифры верны, строка чужая, состав
            # значений тот же.  Так эта порча и выглядит на скане (Э8: 30 из
            # 128 незаметных дефектов).
            стало = [было[-1]] + было[:-1]
            for j, r in enumerate(строки):
                if стало[j] != было[j]:
                    подставить(r["ячейки"][ci], стало[j])
                    ri = t["строки"].index(r)
                    испорчено.add((ti, ri, ci))
    return испорчено


SPOILERS = (
    ("замена цифры", порча_цифра,
     "одна цифра заменена другой; значение осталось правдоподобным"),
    ("сдвиг строки", порча_сдвиг,
     "столбец сдвинут на строку вниз: цифры верны, строка чужая"),
    ("оторванный хвост", порча_хвост,
     "у значения отрезана половина с конца"),
)


# ----------------------------------------------------------------- пометки


def пометка_ne(text, wits):
    """`≠` — чтения разошлись. Считается сводом, `merge.mark_cells`."""
    marked = merge.mark_cells(text, wits)[0]   # Э3 добавил четвёртый довод (пустые)
    doc = разобрать(marked)
    out = set()
    ti = 0
    for вид, тело in doc:
        if вид != "таблица":
            continue
        for ri, r in enumerate(тело["строки"]):
            for ci, c in enumerate(r["ячейки"]):
                if "≠" in c[1]:
                    out.add((ti, ri, ci))
        ti += 1
    return out


def пометка_warn(text, _wits):
    """`⚠` — модель сама не была уверена (вероятности токенов).

    Пометка СТАТИЧЕСКАЯ: она проставлена на арендованной машине по
    логвероятностям и от того, что мы испортили текст, не меняется.  Значит
    её лифт против любой порчи равен единице по построению, и это не изъян
    замера, а свойство пометки, которое надо назвать вслух: `⚠` говорит, где
    модель сомневалась, и ничего не говорит о том, права ли она.
    """
    doc = разобрать(text)
    out = set()
    ti = 0
    for вид, тело in doc:
        if вид != "таблица":
            continue
        for ri, r in enumerate(тело["строки"]):
            for ci, c in enumerate(r["ячейки"]):
                if "⚠" in c[1]:
                    out.add((ti, ri, ci))
        ti += 1
    return out


MARKS = (
    ("≠", пометка_ne, "чтения разошлись; считается сводом при сличении"),
    ("⚠", пометка_warn, "модель сомневалась; проставлена распознавателем"),
)


# ------------------------------------------------------------------- замер


def тексты(outdir):
    """Основа и свидетели — те же, что видит свод.

    Берём ЧЕРНОВИКИ проходов, а не готовую книгу: в книге пометки уже стоят,
    и второй свод дописал бы к ним свои.  Черновик — то, с чего свод
    начинает.
    """
    import glob
    p = layout.Paths(outdir)
    if not p.new:
        raise SystemExit(f"{outdir}: нет passes/ — калибровать нечего")
    def один(d):
        f = layout.draft_of(d)
        if os.path.exists(f):
            return open(f, encoding="utf-8", errors="replace").read()
        pg = sorted(glob.glob(os.path.join(d, "pages", "*.md")))
        return "\n\n".join(open(x, encoding="utf-8", errors="replace").read()
                           for x in pg) if pg else None
    base = один(p.passes[0])
    if base is None:
        raise SystemExit(f"{outdir}: у основы нет ни книги, ни страниц")
    wits = [x for x in (один(d) for d in p.passes[1:]) if x]
    return base, wits


def калибровать(outdir, сколько=200, seed="20260823", повторов=5, verbose=True):
    """Числа калибровки для одной книги.

    Замер повторяется `повторов` раз с разными зёрнами, и величины
    складываются по СЧЁТУ, а не усредняются по долям.  Так пришлось сделать
    после первого же прогона: на одном зерне лифт против сдвига строки вышел
    0.97, на другом 0.81, на третьем 1.20 — то есть у него разброс шире, чем
    расстояние до единицы.  Это само по себе вывод: величина, пляшущая от
    зерна вокруг единицы, — шум, а не сигнал, и предъявлять одно её значение
    нельзя.
    """
    base, wits = тексты(outdir)
    if not wits:
        return {"книга": itog_key(outdir), "беда": "свидетелей нет — сличать нечем"}
    целый = разобрать(base)
    все = адреса(целый)
    if not все:
        return {"книга": itog_key(outdir), "беда": "в книге нет табличных ячеек"}
    итог = {"книга": itog_key(outdir), "ячеек": len(все), "свидетелей": len(wits),
            "зерно": seed, "повторов": повторов, "порчи": {}}
    # Опора считается ОДИН раз: пометки на неиспорченной книге.
    опора = {}
    for имя_метки, метка, _ in MARKS:
        опора[имя_метки] = метка(base, wits)
        итог.setdefault("пометки", {})[имя_метки] = {
            "стоит на ячейках": len(опора[имя_метки] & set(все)),
            "доля": len(опора[имя_метки] & set(все)) / len(все)}

    for имя_порчи, порча, _ in SPOILERS:
        свод = {имя: {"порченых": 0, "помечено на порченых": 0,
                      "чистых": 0, "помечено на чистых": 0,
                      "новых на порченых": 0, "новых на чистых": 0,
                      "пометок до": 0, "пометок после": 0,
                      "лифты": []}
                for имя, _f, _d in MARKS}
        for r in range(повторов):
            rnd = random.Random(f"{seed}:{itog_key(outdir)}:{имя_порчи}:{r}")
            мишени = rnd.sample(sorted(все), min(сколько, len(все)))
            d = копия(целый)
            испорчено = порча(d, мишени, rnd)
            if not испорчено:
                continue
            порченый = собрать(d)
            чистые = set(все) - испорчено
            for имя_метки, метка, _ in MARKS:
                после = метка(порченый, wits)
                a = свод[имя_метки]
                a["порченых"] += len(испорчено)
                a["чистых"] += len(чистые)
                a["помечено на порченых"] += len(после & испорчено)
                a["помечено на чистых"] += len(после & чистые)
                a["новых на порченых"] += len((после - опора[имя_метки]) & испорчено)
                a["новых на чистых"] += len((после - опора[имя_метки]) & чистые)
                a["пометок до"] += len(опора[имя_метки])
                a["пометок после"] += len(после)
                ф = len(после & чистые) / max(len(чистые), 1)
                п = len(после & испорчено) / max(len(испорчено), 1)
                a["лифты"].append(п / ф if ф else None)
        строка = {}
        for имя_метки in свод:
            a = свод[имя_метки]
            фон = a["помечено на чистых"] / max(a["чистых"], 1)
            поймано = a["помечено на порченых"] / max(a["порченых"], 1)
            лифты = [x for x in a["лифты"] if x is not None]
            строка[имя_метки] = {
                "фон": фон, "поймано": поймано,
                "лифт": (поймано / фон) if фон else None,
                "лифт мин": min(лифты) if лифты else None,
                "лифт макс": max(лифты) if лифты else None,
                "испорчено ячеек": a["порченых"],
                "новых пометок на порче": a["новых на порченых"],
                "новых пометок на чистых": a["новых на чистых"],
                # Главная величина для сдвига строки: меняется ли ЧИСЛО
                # пометок в книге вообще.  Ноль означает, что свод не заметил
                # порчи ни на грош, а всё «пойманное» — старые пометки,
                # переехавшие на другие ячейки внутри той же области.
                "пометок в книге стало больше на":
                    a["пометок после"] - a["пометок до"],
            }
        строка["испорчено ячеек"] = свод[MARKS[0][0]]["порченых"]
        строка.update({k: v for k, v in строка[MARKS[0][0]].items()
                       if k in ("фон", "поймано", "лифт")})
        итог["порчи"][имя_порчи] = строка
        if verbose:
            n = строка["≠"]
            л, лн, лм = n["лифт"], n["лифт мин"], n["лифт макс"]
            print(f"  {имя_порчи:18s} испорчено {n['испорчено ячеек']:5d}  "
                  f"фон {n['фон']:6.1%}  поймано {n['поймано']:6.1%}  лифт "
                  + ("—" if л is None else f"{л:5.2f}")
                  + (f" (по прогонам {лн:.2f}–{лм:.2f})" if лн is not None else "")
                  + f"   пометок в книге +{n['пометок в книге стало больше на']}, "
                    f"новых на порче {n['новых пометок на порче']}")
    return итог


def itog_key(outdir):
    return os.path.basename(os.path.abspath(outdir))


# ------------------------------------------- сведение с ручной разметкой Э8


def свести_с_разметкой(outdir, tsv, книга=None):
    """Лифт `≠` против ручной разметки ошибок, а не против себя.

    Требование Э8 дословно: «показать лифт `≠` против ручной разметки ошибок,
    а не против самого себя».  Калибровка выше меряет пометку против ПОРЧИ,
    которую нанесли мы; здесь — против порчи, которую нанесла модель и
    которую человек нашёл глазами по вырезкам скана.

    Сопоставление грубое нарочно: значение из колонки «книга(проход1)»
    ищется среди значений ячеек книги.  Строки с многоточием (`…`) режутся по
    нему; короче четырёх знаков не берём — `14` есть в каждой таблице.
    """
    книга = книга or itog_key(outdir)
    p = layout.Paths(outdir)
    text = open(p.book, encoding="utf-8", errors="replace").read()
    doc = разобрать(text)
    все = адреса(doc)
    помечено = пометка_ne_из_книги(doc)
    фон = len(помечено) / max(len(все), 1)

    искомые = []
    with open(tsv, encoding="utf-8") as f:
        head = next(f)
        for line in f:
            q = line.rstrip("\n").split("\t")
            if len(q) < 9 or q[0] != книга:
                continue
            v = q[4].split("…")[0].strip()
            if len(v) >= 4 and v not in ("пусто", "потеряны", "потеряно"):
                искомые.append((q[1], q[2], v, q[8]))
    if not искомые:
        return None
    нашли = 0
    сней = 0
    поимённо = []
    норм = {a: re.sub(r"\s+", " ", v) for a, v in все.items()}
    for табл, вид, v, разряд in искомые:
        vv = re.sub(r"\s+", " ", v)
        адрес = next((a for a, x in норм.items()
                      if x == vv or x.startswith(vv) or vv.startswith(x) and len(x) >= 4),
                     None)
        if адрес is None:
            continue
        нашли += 1
        есть = адрес in помечено
        сней += есть
        поимённо.append((табл, вид, v[:40], разряд, есть))
    return {"книга": книга, "фон": фон, "ячеек в книге": len(все),
            "дефектов из разметки": len(искомые), "нашлось в книге": нашли,
            "из них помечено ≠": сней,
            "доля": сней / max(нашли, 1),
            "лифт": (сней / max(нашли, 1)) / фон if фон else None,
            "поимённо": поимённо}


def пометка_ne_из_книги(doc):
    out, ti = set(), 0
    for вид, тело in doc:
        if вид != "таблица":
            continue
        for ri, r in enumerate(тело["строки"]):
            for ci, c in enumerate(r["ячейки"]):
                if "≠" in c[1]:
                    out.add((ti, ri, ci))
        ti += 1
    return out


