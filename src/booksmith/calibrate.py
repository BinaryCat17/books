def cmd_calibrate(a):
    import json
    итоги = []
    for d in a.outdir:
        print(f"=== {os.path.relpath(d)}")
        it = калибровать(d, сколько=a.cells, seed=a.seed,
                         повторов=a.repeats)
        итоги.append(it)
        if "порчи" in it:
            # Числа кладём в run.json: отчёт книги читает их оттуда и
            # печатает «ФОН» там, где лифт ниже трёх.  Без этого калибровка
            # осталась бы разговором в терминале.
            layout.remember(d, **{"калибровка": {
                "зерно": a.seed, "ячеек": it["ячеек"],
                "повторов": a.repeats,
                "порчи": {k: {"фон": v["≠"]["фон"], "поймано": v["≠"]["поймано"],
                              "лифт": v["≠"]["лифт"],
                              "испорчено ячеек": v["≠"]["испорчено ячеек"],
                              "новых пометок на порче":
                                  v["≠"]["новых пометок на порче"],
                              "пометок в книге стало больше на":
                                  v["≠"]["пометок в книге стало больше на"]}
                          for k, v in it["порчи"].items()}}})
        if a.errors:
            св = свести_с_разметкой(d, a.errors)
            if св:
                it["сведение с Э8"] = св
                print(f"  разметка Э8: дефектов {св['дефектов из разметки']}, "
                      f"нашлось {св['нашлось в книге']}, помечено ≠ "
                      f"{св['из них помечено ≠']} ({св['доля']:.1%}) при фоне "
                      f"{св['фон']:.1%} -> лифт "
                      + ("—" if св["лифт"] is None else f"{св['лифт']:.2f}"))
    if a.json:
        with open(a.json, "w", encoding="utf-8") as f:
            json.dump(итоги, f, ensure_ascii=False, indent=1, default=str)
        print(f"числа: {a.json}")
    # Код возврата: 1, если хоть у одной книги хоть одна пометка оказалась
    # фоном.  Калибровка, которая всегда возвращает 0, — это отчёт, а не
    # проверка.
    плохо = [f"{it['книга']}/{k}" for it in итоги
             for k, v in (it.get("порчи") or {}).items()
             if (v.get("лифт") or 0) < 3.0]
    if плохо:
        print(f"\nпометка `≠` оказалась ФОНОМ против: {', '.join(плохо)}")
        return 1
    return 0
