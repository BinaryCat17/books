#!/usr/bin/env bash
# Разворачивание окружения на арендованной машине — то, что раньше было
# слоями образа.
#
# Почему не слоями: docker качает три слоя одновременно и по одному потоку на
# слой, а реестр режет соединение до ~25 Мбит/с — итого 76 Мбит/с потолка
# независимо от канала машины.  Замерено: 6.02 ГБ образа ехали 10.7 минуты.
# uv и hf открывают десятки соединений; те же 11 ГБ ставятся за 82 секунды,
# то есть почти насыщают канал в 1500 Мбит/с.
#
# Скрипт идемпотентен: на прогретой машине (--reuse) всё уже на месте, и он
# отрабатывает за секунды.  Каждый шаг печатает своё время — чтобы «старт
# долгий» всегда разбирался на конкретный шаг.
set -euo pipefail

ENVDIR=${ENVDIR:-/opt/env}
MODELS=${MODELS:-/models}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

export UV_LINK_MODE=copy
export UV_HTTP_TIMEOUT=180
export HF_HUB_DISABLE_PROGRESS_BARS=1

step() {
    local label="$1"; shift
    local t0 t1
    t0=$(date +%s)
    "$@"
    t1=$(date +%s)
    printf '== %-18s %4dс\n' "$label" "$((t1 - t0))"
}

step "python" uv python install 3.12
# --allow-existing обязателен: на прогретой машине (--reuse, или та же
# машина под тем же тегом) каталог уже есть, и uv без этого флага падает с
# "A virtual environment already exists at: /opt/env", то есть ровно на том
# сценарии, ради которого скрипт и писался идемпотентным.
step "окружение" uv venv "$ENVDIR" --python 3.12 --allow-existing

export VIRTUAL_ENV="$ENVDIR"
export PATH="$ENVDIR/bin:$PATH"

# Ставится constraints.txt — закреплённое дерево целиком, а не верхний
# уровень: иначе разрешение зависимостей идёт здесь, на арендованной карте,
# и новый релиз любой транзитивной зависимости роняет книгу на середине.
# requirements.in остаётся входом для пересборки этого файла, см. его шапку.
#
# --torch-backend=cu130 нужен и здесь: версия закреплена как 2.13.0+cu130,
# а такой на PyPI нет — она лежит в индексе pytorch.
step "колёса" uv pip install -r "$HERE/constraints.txt" --torch-backend=cu130

# РЕПОЗИТОРИЙ 1.6, А НЕ ПРОСТО PaddleOCR-VL. Здесь стояло
# `PaddlePaddle/PaddleOCR-VL` — это ДРУГИЕ, более старые веса, а ручка
# `MODEL_NAME` при этом объявляет `PaddleOCR-VL-1.6-0.9B`, и `vllm serve
# --served-model-name` заставляет сервер называться как велено. То есть
# прогон вышел бы успешным и неверным: слепок назвал бы версию, которой не
# считал, а проверка имени модели этого не поймала бы по построению — она
# доказывает, что мы попали на СВОЙ сервер, и не доказывает, какие под ним
# веса. Доказывает их только отпечаток чтеца, снятый рядом с ними
# (sha256 config.json, `models/paddleocr_vl/reader.py`).
VL_REPO="${VL_REPO:-PaddlePaddle/PaddleOCR-VL-1.6}"
step "веса VL" hf download "$VL_REPO" --local-dir "$MODELS/vl"
# ОТКУДА ИМЕННО ВЗЯТЫ ВЕСА — файлом рядом с ними, а не в памяти оболочки.
# Без этого доказать версию нечем: `config.json` у 1.6 и у старого
# `PaddleOCR-VL` СОВПАДАЕТ ПОБАЙТОВО (sha256 ce7f4565…, 2059 байт), то есть
# сторож, который его хэшировал, не мог поймать ровно тот прогон, ради
# которого писался. Различаются `tokenizer_config.json`, `chat_template.jinja`,
# `preprocessor_config.json` — но надёжнее не гадать, а записать имя.
printf '{"repo": "%s"}\n' "$VL_REPO" > "$MODELS/vl/SOURCE.json"
# ВЕСА ДЕТЕКТОРА БОЛЬШЕ НЕ КАЧАЮТСЯ, и это 214 МБ на каждый прогон.
# Детекция делается ДОМА, на процессоре и бесплатно, а на бокс приезжает
# готовым каталогом `detect/` — рамки, ярлыки, порядок. Здесь оставался шаг от
# прежней задачи, когда макет считался на карте: `hf download
# PaddlePaddle/PP-DocLayoutV2_onnx --local-dir /models/layout`. Ни один
# потребитель этих весов на боксе не поднимается — `LAYOUT_MODEL_DIR` не
# читает никто, `books read` детектор не зовёт вовсе.
