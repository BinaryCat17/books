"""The documents rendered from the code: commands, knobs, metrics.

`books docs` writes them; `tests/test_docs.py` regenerates and compares, so a
committed copy that drifts from the code is red. `METRICS.md` is generated
too, by `books bench report` from `results/`, and is listed here so the
documents test knows which files are not prose.
"""
import argparse
import os

from booksmith.core import knobs

GENERATED = ("docs/commands.md", "docs/knobs.md", "docs/metrics.md", "METRICS.md")
HEADER = "<!-- generated by `books docs`; edit the code, not this file -->\n\n"


def _subparsers(parser, prefix=""):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, sub in action.choices.items():
                yield prefix + name, sub
                yield from _subparsers(sub, prefix + name + " ")


def commands(parser) -> str:
    out = [HEADER, "# Commands\n\n```\n", parser.format_help(), "```\n"]
    for name, sub in _subparsers(parser):
        out.append(f"\n## books {name}\n\n```\n{sub.format_help()}```\n")
    return "".join(out)


def knobs_doc() -> str:
    out = [HEADER, "# Knobs\n\n",
           "Every knob, declared in `src/booksmith/core/knobs.py`. "
           "An empty default means unset.\n"]
    for k in knobs.KNOBS:
        debt = " (declared, read by nothing yet)" if k.debt else ""
        out.append(f"\n## {k.name}\n\ndefault: `{k.default}`{debt}\n\n{k.what}\n")
    return "".join(out)


def metrics_doc() -> str:
    from booksmith.datasets import metrics as registry
    out = [HEADER, "# Metrics\n\n",
           "Every registered metric and what it needs from a bench and a run. "
           "The numbers are in `METRICS.md`.\n"]
    for m in registry.METRICS:
        doc = (type(m).__doc__ or "").strip().split("\n\n")[0]
        doc = " ".join(line.strip() for line in doc.splitlines())
        needs = ", ".join(sorted(m.needs)) or "nothing"
        out.append(f"\n## {m.name}\n\nneeds: {needs}\n\n{doc}\n")
    return "".join(out)


def render_all(parser) -> dict:
    """Relative path -> text, for every document `books docs` owns."""
    # argparse wraps help to the terminal width; pinned so the file is the
    # same on every machine.
    was = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = "80"
    try:
        return {"docs/commands.md": commands(parser),
                "docs/knobs.md": knobs_doc(),
                "docs/metrics.md": metrics_doc()}
    finally:
        if was is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = was


def write_all(parser, root: str) -> list:
    written = []
    for rel, text in render_all(parser).items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        written.append(rel)
    return written
