"""Годен ли вывод модели, чтобы гнать через него OCR не теряя смысла.

Прежние два числа отвечают на другие вопросы. «Обвёл точно» (двустороннее
покрытие 0.75) меряет ТОЧНОСТЬ рамки и штрафует за слияние — а для нашего
конвейера слияние не потеря: во второй уровень уедет картинка пошире, и он
разберёт её на два блока. «Смысл цел» штрафует слияние тоже. Оба поэтому
занижают годность, и занижают сильно: на 36 самых трудных страницах золотого
стенда первое даёт 20%, а объектов, которые доедут до второго уровня
неповреждёнными, — 82%.

Здесь считается ровно то, от чего зависит результат:

  ЧЕРНИЛА. Какая доля тёмных пикселей объекта лежит внутри рамок артефактного
  разряда. Аргумент «рамка теснее эталонной» этим снят раз и навсегда: поле
  вокруг рисунка чернил не содержит, и его потеря не стоит ничего, а вот
  отрезанная строка таблицы не восстановится ничем. Замер на золотом стенде
  показал, чего стоит разница: dots.ocr по строгому совпадению впереди всех
  (37% против 20%), а по чернилам ПОЗАДИ — 88.6% против 94.8%, потому что
  обводит теснее эталона и режет содержимое.

  ОДНОЙ РАМКОЙ ИЛИ ДВУМЯ. Объект, целиком попавший в ОДНУ рамку, вырежется
  одной картинкой — и неважно, попал ли с ним сосед. Объект, разъехавшийся по
  двум рамкам, приедет двумя кусками, и таблица распадётся.

  РАЗРЯД. Объект, накрытый только текстовыми рамками, во второй уровень не
  поедет вовсе: он уедет строкой текста, и структура пропадёт. Это отдельная
  беда от «не увиден», и чинится она ярлыком, а не моделью.

ЧЕМ ЭТО ЛОМАЕТСЯ. Одна рамка во весь лист даёт 100% чернил и 100% объектов
целиком. Поэтому рядом печатается ПЛОЩАДЬ ПОД РАМКАМИ: у честной разметки она
заметно меньше листа, у вырожденной — равна ему. Без этого числа метрику
можно выиграть, ничего не найдя.

ИСТИНА ЗДЕСЬ НЕ ОБЯЗАТЕЛЬНА. Без неё считается то же по чернилам ВСЕЙ
страницы: сколько их осталось вне всех рамок вообще, то есть что просто
исчезнет из HTML. Это работает на любой книге, которую ещё никто не размечал.
"""
import os

import numpy as np
import pymupdf

from . import metrics, policy

# Порог «это чернила»: пиксель темнее — содержимое, светлее — бумага. Тот же
# INK, что у синтетического стенда, где по нему меряется истина.
INK = 160
# Доли, по которым объекты разносятся на разряды сохранности. Названы числом
# и печатаются в отчёте: где кончается «цел» и начинается «надкушен», решаем
# мы, и решение обязано быть видно.
WHOLE, ALMOST, BITTEN = 0.99, 0.95, 0.80
# Ширина краевой полосы, в долях меньшей стороны листа.
EDGE = 0.04


# Растр страницы не меняется от прогона к прогону, а батарея гоняет метрику
# семь раз подряд. Без памяти семь одинаковых рендеров 600 страниц — это
# полчаса счёта ни за чем.
# Память ограничена нарочно: 600 страниц золотого стенда в булевых масках —
# это около гигабайта, и без потолка батарея убила бы машину раньше, чем
# досчитала. Потолок в страницах, а не в байтах: он виден и повторяем.
_INK_CACHE = {}
_INK_CACHE_MAX = 64


def _ink_of(pdf, doc, i, dpi):
    key = (pdf, i, int(dpi))
    if key not in _INK_CACHE:
        if len(_INK_CACHE) >= _INK_CACHE_MAX:
            _INK_CACHE.clear()
        _INK_CACHE[key] = _ink(doc[i], dpi)
    return _INK_CACHE[key]


def _ink(page, dpi):
    pm = page.get_pixmap(dpi=int(dpi))
    g = np.frombuffer(pm.samples, np.uint8).reshape(pm.height, pm.width, pm.n)
    g = g[:, :, :3].mean(2) if pm.n >= 3 else g[:, :, 0]
    return g < INK


def _mask(shape, boxes):
    m = np.zeros(shape, bool)
    for x0, y0, x1, y1 in boxes:
        m[max(0, int(y0)):int(y1) + 1, max(0, int(x0)):int(x1) + 1] = True
    return m


def measure(pdf: str, detect_dir: str, truth_dir: str = "") -> dict:
    """Годность вывода модели. Истина не обязательна."""
    if not os.path.exists(pdf):
        raise metrics.MetricError(f"нет {pdf}")
    M = metrics._load(detect_dir)
    T = metrics._load(truth_dir) if truth_dir else {}
    doc = pymupdf.open(pdf)
    res = {"страниц": 0, "чернил всего": 0, "чернил под рамками": 0,
           "чернил под артефактом": 0, "площадь листа": 0, "площадь рамок": 0,
           "чернил вне рамок у края": 0,
           "объектов": 0, "чернил объектов": 0, "чернил объектов в рамках": 0,
           "цел": 0, "почти цел": 0, "надкушен": 0, "порван": 0,
           "одной рамкой": 0, "разорван между рамками": 0, "уехал текстом": 0,
           "пустых объектов": 0, "пороги": {"чернила": INK, "цел": WHOLE,
                                            "почти": ALMOST, "надкушен": BITTEN}}
    pages = sorted(T) if T else sorted(M)
    for i in pages:
        if i not in M:
            raise metrics.MetricError(
                f"модель не разметила страницу {i}: считать нечего. "
                f"Пустой ответ тут выглядел бы как «чернил не потеряно».")
        p = M[i]
        ink = _ink_of(pdf, doc, i, p["dpi"])
        if ink.shape != (p["height"], p["width"]):
            raise metrics.MetricError(
                f"страница {i}: растр {ink.shape[1]}x{ink.shape[0]}, "
                f"разметка {p['width']}x{p['height']} — рамки лягут мимо")
        arte = [b["box"] for b in p["blocks"]
                if policy.role(b["label"]) == "артефакт"]
        rest = [b["box"] for b in p["blocks"]
                if policy.role(b["label"]) != "артефакт"]
        ma, mr = _mask(ink.shape, arte), _mask(ink.shape, rest)
        both = ma | mr
        res["страниц"] += 1
        res["чернил всего"] += int(ink.sum())
        res["чернил под рамками"] += int((ink & both).sum())
        res["чернил под артефактом"] += int((ink & ma).sum())
        # Половина «потерянных» чернил золотого стенда лежит в четырёхпроцентной
        # полосе у края листа — это тёмная кромка скана, а не содержимое.
        # Считаем её отдельно: без этого числа чёрная кайма читается как
        # «модель потеряла четверть книги».
        out = ink & ~both
        h, w = ink.shape
        k = max(1, int(min(h, w) * EDGE))
        edge = np.zeros_like(out)
        edge[:k] = edge[-k:] = True
        edge[:, :k] = edge[:, -k:] = True
        res["чернил вне рамок у края"] += int((out & edge).sum())
        res["площадь листа"] += ink.size
        res["площадь рамок"] += int(both.sum())
        for b in T.get(i, {}).get("blocks", []):
            if policy.role(b["label"]) != "артефакт":
                continue
            x0, y0, x1, y1 = (int(v) for v in b["box"])
            sub = ink[max(0, y0):y1 + 1, max(0, x0):x1 + 1]
            tot = int(sub.sum())
            if tot == 0:
                # Объект без чернил — это дефект СТЕНДА, а не модели, и он
                # обязан считаться отдельно: спрятав его в «цел», мы дали бы
                # модели незаслуженное очко, а спрятав в «порван» — незаслуженный
                # промах.
                res["пустых объектов"] += 1
                continue
            res["объектов"] += 1
            res["чернил объектов"] += tot
            win = (slice(max(0, y0), y1 + 1), slice(max(0, x0), x1 + 1))
            kept = int((sub & ma[win]).sum())
            res["чернил объектов в рамках"] += kept
            r = kept / tot
            res["цел" if r >= WHOLE else "почти цел" if r >= ALMOST
                else "надкушен" if r >= BITTEN else "порван"] += 1
            # «Одной рамкой» СЧИТАЕТСЯ ПО ТЕМ ЖЕ ЧЕРНИЛАМ, что и «цел», разница
            # только в том, сколько рамок держит объект: объединение или одна.
            # Оттого числа вложены строго — целых не меньше, чем вырезаемых
            # одной картинкой, — и разность между ними имеет имя.
            #
            # Прежняя редакция считала «одной рамкой» по ГЕОМЕТРИИ рамки, а
            # «цел» по чернилам, и вложенность ломалась: 92 объекта золотого
            # стенда были «без потерь», не будучи «вырезаемыми целиком», и
            # столько же наоборот. Два числа на разных основаниях в одной
            # строке — это не строгость, а путаница.
            best = 0
            for x in arte:
                one = int((sub & _mask(ink.shape, [x])[win]).sum())
                if one > best:
                    best = one
                    if best == tot:
                        break
            if best / tot >= WHOLE:
                res["одной рамкой"] += 1
            elif r >= WHOLE:
                res["разорван между рамками"] += 1
            # Диагноз, а не разряд: объект, которого рамки артефактов не держат,
            # но текстовые держат целиком. Он не потерян — он поедет строкой,
            # и структура пропадёт. Чинится ярлыком, а не моделью.
            if r < WHOLE:
                t_kept = int((sub & mr[win]).sum())
                if (t_kept + kept) / tot >= WHOLE:
                    res["уехал текстом"] += 1
    doc.close()
    return res


def report(res: dict, log=print) -> None:
    n, s = res["объектов"], res["страниц"]
    ink_all = max(1, res["чернил всего"])
    log(f"страниц {s}; порог чернил {INK}, «цел» от {WHOLE:.2f} чернил объекта")
    log(f"чернил страницы под рамками: "
        f"{res['чернил под рамками'] / ink_all * 100:.1f}% "
        f"(под артефактом {res['чернил под артефактом'] / ink_all * 100:.1f}%), "
        f"вне всех рамок "
        f"{(1 - res['чернил под рамками'] / ink_all) * 100:.1f}% — это то, "
        f"что исчезнет из HTML")
    lost = ink_all - res["чернил под рамками"]
    if lost > 0:
        log(f"  из потерянного {res['чернил вне рамок у края'] / lost * 100:.0f}% "
            f"лежит в полосе {EDGE * 100:.0f}% у края листа — обычно это "
            f"тёмная кромка скана, а не содержимое")
    log(f"площадь под рамками {res['площадь рамок'] / max(1, res['площадь листа']) * 100:.0f}% "
        f"листа — при 100% числа выше ничего не значат: рамка во весь лист "
        f"выигрывает замер, не найдя ничего")
    if not n:
        log("истина не подана: по объектам сказать нечего — это не ноль потерь")
        return
    log(f"ЧЕРНИЛ ОБЪЕКТОВ СОХРАНЕНО: "
        f"{res['чернил объектов в рамках'] / max(1, res['чернил объектов']) * 100:.1f}%")
    log(f"объектов {n}: цел {res['цел']} ({res['цел'] / n * 100:.0f}%), "
        f"почти цел {res['почти цел']}, надкушен {res['надкушен']}, "
        f"порван {res['порван']}")
    log(f"вырезается одной картинкой {res['одной рамкой']} "
        f"({res['одной рамкой'] / n * 100:.0f}%); "
        f"разорван между рамками {res['разорван между рамками']}; "
        f"уехал текстом {res['уехал текстом']}")
    if res["пустых объектов"]:
        log(f"ВНИМАНИЕ: {res['пустых объектов']} объектов истины без чернил — "
            f"это дефект стенда, они не считаны ни в цел, ни в порван")


# ------------------------------------------------- батарея порчи
# Числу верить нельзя, пока не показано, что оно умеет упасть. Каждая проба
# портит ОДНУ вещь и называет, чему полагается сдвинуться.
def _edit(M, fn):
    return {i: {**p, "blocks": [b for b in map(fn, p["blocks"]) if b]}
            for i, p in M.items()}


def _scale(b, f):
    x0, y0, x1, y1 = b["box"]
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    w, h = (x1 - x0) * f / 2, (y1 - y0) * f / 2
    return {**b, "box": [cx - w, cy - h, cx + w, cy + h]}


def mutations(pdf: str, detect_dir: str, truth_dir: str = "", log=print) -> int:
    """Подать в метрику заведомо испорченное и убедиться, что число упало."""
    import json
    import tempfile

    base = measure(pdf, detect_dir, truth_dir)
    M0 = metrics._load(detect_dir)

    def R(M):
        d = tempfile.mkdtemp()
        for i, p in M.items():
            with open(os.path.join(d, f"{i:04d}.json"), "w",
                      encoding="utf-8") as f:
                json.dump(p, f, ensure_ascii=False)
        return measure(pdf, d, truth_dir)

    art = lambda b: policy.role(b["label"]) == "артефакт"
    page = lambda b, p: {**b, "box": [0, 0, p["width"], p["height"]]}
    full = {i: {**p, "blocks": [page(b, p) for b in p["blocks"][:1]] or
                               [{"box": [0, 0, p["width"], p["height"]],
                                 "label": "image", "block_id": 0, "order": 0,
                                 "score": None, "content": None,
                                 "kind": "none"}]}
            for i, p in M0.items()}
    def _halve(M):
        """Каждую рамку артефакта — на две половины впритык.

        Чернила при этом не теряются: объединение накрывает ровно то же. А вот
        ОДНОЙ картинкой объект уже не вырежется — он приедет двумя кусками.
        Проба целится ровно в разницу между «без потерь» и «вырежется целиком»:
        без неё эту разницу нечем было бы проверить.
        """
        out = {}
        for i, p in M.items():
            bl = []
            for b in p["blocks"]:
                if policy.role(b["label"]) != "артефакт":
                    bl.append(b)
                    continue
                x0, y0, x1, y1 = b["box"]
                cx = (x0 + x1) / 2
                bl.append({**b, "box": [x0, y0, cx, y1]})
                bl.append({**b, "box": [cx, y0, x1, y1]})
            out[i] = {**p, "blocks": bl}
        return out

    probes = [
        ("рамки артефактов разрезаны пополам", "вырезаемых одной картинкой меньше",
         lambda: None if not base["объектов"] else
                 R(_halve(M0))["одной рамкой"] < base["одной рамкой"]),
        ("рамки артефактов разрезаны пополам", "чернил при этом не потеряно",
         lambda: None if not base["объектов"] else
                 R(_halve(M0))["чернил объектов в рамках"]
                 >= base["чернил объектов в рамках"]),
        ("вложенность", "вырезаемых одной картинкой не больше, чем целых",
         lambda: base["одной рамкой"] <= base["цел"]),
        ("рамок нет вовсе", "чернил под рамками ноль",
         lambda: R(_edit(M0, lambda b: None))["чернил под рамками"] == 0),
        # Сторож `None if not base["объектов"]` — тот же, что у соседей выше и
        # ниже, и здесь его не было. Цена пропуска: без `--truth` объектов
        # нет, «чернил объектов в рамках» равно нулю и до порчи, и после,
        # `0 < 0` даёт False, и батарея печатала «НЕ поймана» — то есть
        # обвиняла прибор там, где мерить нечем. Замер: шесть книг из шести,
        # `books fitness … --selfcheck` без `--truth` возвращал 1. Это ровно
        # слитые два нуля, о которых предупреждает отчёт в этом же файле:
        # «истина не подана: по объектам сказать нечего — это не ноль потерь».
        ("рамки сжаты вдвое", "чернил объектов сохранено меньше",
         lambda: None if not base["объектов"] else
                 R(_edit(M0, lambda b: _scale(b, 0.5)))["чернил объектов в рамках"]
                 < base["чернил объектов в рамках"]),
        ("артефакты названы текстом", "чернил под артефактом ноль",
         lambda: R(_edit(M0, lambda b: {**b, "label": "text"}))
                 ["чернил под артефактом"] == 0),
        ("артефакты названы текстом", "объекты уехали текстом",
         lambda: None if not base["объектов"] else
                 R(_edit(M0, lambda b: {**b, "label": "text"}))["уехал текстом"]
                 > base["уехал текстом"]),
        ("рамки выкинуты, кроме текстовых", "целых меньше",
         lambda: None if not base["объектов"] else
                 R(_edit(M0, lambda b: None if art(b) else b))["цел"] < base["цел"]),
        # Сторож вырожденного ответа: рамка во весь лист выигрывает по чернилам
        # и обязана быть видна по площади. Без этой пробы метрику можно взять
        # одной рамкой, не найдя ничего.
        ("одна рамка во весь лист", "чернил 100%, но и площадь 100%",
         lambda: (lambda r: r["чернил под рамками"] == r["чернил всего"]
                  and r["площадь рамок"] == r["площадь листа"])(R(full))),
    ]
    bad = 0
    for name, expect, fn in probes:
        try:
            ok = fn()
        except Exception as e:
            ok, expect = False, f"{expect} — упало: {type(e).__name__}: {e}"
        mark = "нет данных" if ok is None else ("ok " if ok else "НЕТ")
        log(f"  {mark:>11}  {name}: {expect}")
        bad += ok is False
    log(f"батарея годности: проб {len(probes)}, непойманных {bad}")
    return bad
