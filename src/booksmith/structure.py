FIGURE_WORDS = ("Fig", "Figure", "Рис", "Рисунок", "Фиг", "Фигура", "Илл",
                "Иллюстрация", "Abb", "Abbildung", "Plate", "Photo", "Схема")
TABLE_WORDS = ("Table", "Таблица", "Табл", "Tabelle", "Tab")
# Продолжение таблицы через разрыв страницы — тоже подпись, а не заголовок.
CONT_WORDS = ("Продолжение", "Окончание", "continued", "cont'd")


def _spaced(word):
    """`Фиг` -> `Ф\\s*и\\s*г`: разрядка оригинала не должна ломать опознание."""
    return r"\s*".join(re.escape(c) for c in word)


def _words_re(words):
    return "(?:" + "|".join(_spaced(w) for w in words) + r")[.,]?"


# Номер подписи: `4.2`, `I.31`, `1-1`, `10-13`, `39`, `VIII.19a`.
_CAP_NUM = rf"(?:{_RN}|\d+)(?:\s*[.\-–—]\s*(?:{_RN}|\d+))*[a-zа-я]?"
FIG_HEAD = re.compile(rf"^(?:<[^>]+>\s*)*{_words_re(FIGURE_WORDS)}\s*"
                      rf"({_CAP_NUM})\b", re.I)
TBL_HEAD = re.compile(rf"^(?:<[^>]+>\s*)*(?:{_words_re(CONT_WORDS)}\s*)?"
                      rf"{_words_re(TABLE_WORDS)}\s*({_CAP_NUM})\b", re.I)
# Ссылка на рисунок внутри строки — то же слово, но не в начале абзаца.
FIG_REF = re.compile(rf"{_words_re(FIGURE_WORDS)}\s*({_CAP_NUM})", re.I)


def _num_ok(t):
    """Похож ли хвост подписи на НОМЕР, а не на первое слово названия.

    Проверка несущая, а не косметическая: римские буквы в `_RN` — это ещё и
    кириллические двойники (`С`, `В`, `М`, `Х`, `У`), поэтому без неё
    «Схема Синтеза» и «Табл. Свойства» опознавались бы как подпись с номером
    «С», и настоящий заголовок уезжал бы в прозу.
    """
    t = (t or "").strip()
    if not t:
        return False
    if any(c.isdigit() for c in t):
        return True
    return chapter_number(t.split()[0].strip(".,")) is not None


# Голое слово подписи без номера — тоже подпись, а не раздел: над таблицей,
# у которой номера нет, набрано просто «Таблица».  У «Кристаллизации» таких
# семь, и все семь стояли в оглавлении наравне с главами.
BARE_CAP = re.compile(rf"^(?:<[^<>]*>\s*)*(?:{_words_re(TABLE_WORDS)}|"
                      rf"{_words_re(FIGURE_WORDS)})\s*$", re.I)


def caption_kind(text):
    """`fig` / `tbl` / None — подпись это к рисунку, к таблице или не подпись."""
    if BARE_CAP.match((text or "").strip()):
        return "tbl"
    m = TBL_HEAD.match(text or "")
    if m and _num_ok(m.group(1)):
        return "tbl"
    m = FIG_HEAD.match(text or "")
    if m and _num_ok(m.group(1)):
        return "fig"
    return None
