def restructure(outdir):
    """Собрать структуру в `book.md`, написать оглавление и отчёт.

    Повторный запуск ничего не меняет: правки идемпотентны, и во второй раз
    счётчики выходят нулевыми.  Это не украшение, а условие — шаг должен
    переживать `books restructure` на уже собранной книге.
    """
    p = layout.Paths(outdir)
    if not p.new and os.path.basename(os.path.dirname(p.outdir)) == layout.PASSES:
        # Шаг переписывает книжный файл НА МЕСТЕ, а внутри прохода это
        # черновик, из которого собирается книга.  Замер: после
        # `books restructure passes/1` пересборка дала на семь абзацев больше
        # несверенных — склейка переносов разошлась с текстом свидетелей.
        # «Посмотреть, что дал проход» оказалось разрушительным действием.
        raise SystemExit(
            f"{outdir} — это проход, а не книга. Шаг переписывает текст на "
            f"месте и испортит основу свода. Собирайте книгу: "
            f"books merge {os.path.dirname(os.path.dirname(p.outdir))}")
    book = p.book
    if not os.path.exists(book):
        raise SystemExit(f"нет разбора: {book}")

    src = open(book, encoding="utf-8").read()

    # Слепок до сборки структуры пишем сами и один раз.  До сих пор он
    # существовал только потому, что его сняли руками, и это было чистой
    # удачей: шаг переписывает `book.md` на месте, а разбор стоит денег и
    # точно не воспроизводится.  Заодно он даёт отчёту опору: сравнивать
    # надо с исходным разбором, а не с предыдущим запуском — иначе на
    # повторном прогоне все величины сравниваются сами с собой и отчёт
    # рапортует «склеено переносов 0» там, где склеено 139.
    snap = p.snapshot
    if not os.path.exists(snap):
        open(snap, "w", encoding="utf-8").write(src)
        print(f"  слепок до сборки: {os.path.basename(snap)}")
    # Собираем структуру ВСЕГДА ИЗ СЛЕПКА, а не из книги на диске.
    #
    # Иначе отчёт говорит не про книгу, а про запуск, и врёт при обычном
    # порядке работы: `books merge` уже зовёт сборку структуры сам, поэтому
    # у оператора, идущего по CLAUDE.md (`merge`, потом `restructure`),
    # второй запуск и есть тот, чей отчёт доезжает до читателя.  Замер на
    # стенде «Справочника»: первый запуск «склеено переносов 4, колонцифр
    # возвращено 12, номеров формул 6, проходов сборки 2», второй — «0, 0,
    # 0, проходов 1», и покрытие метки `footer` прыгает 0% -> 100%.  Ноль
    # от повтора неотличим от ноля-от-нечего-склеивать.
    #
    # Шаг доказанно идемпотентен ПО ТЕКСТУ (книга и оглавление байт в байт),
    # поэтому пересборка из слепка даёт ту же книгу — и те же числа.  Цена:
    # правка, внесённая руками в `<книга>.md` поверх сборки структуры, будет
    # перезаписана.  Молча этого не делаем: расхождение считается и
    # называется строками (ниже, «книга на диске отличалась от собранной»).
    правленое = None
    снимок = open(snap, encoding="utf-8").read()
    if снимок != src:
        правленое, src = src, снимок
    before = _measure(снимок)
    blks = blocks(p.pages)
    if not blks:
        raise SystemExit(f"нет json страниц в {p.pages} — "
                         f"структуру брать неоткуда")

    # Целостность скана — по колонцифрам, до всякой правки текста.  Тексты
    # страниц читаются только для листов, попавших под подозрение: у шести
    # книг это 32 листа из 3268.
    nums = page_numbers(blks)

    def _pt(name):
        f = os.path.join(p.pages, name + ".md")
        try:
            return open(f, encoding="utf-8").read()
        except OSError:
            return ""

    lstat, defects, misread = scan_ladder(nums, _pt)
    suspect = {x[0] for x in misread}

    body, kept = _protect(src)
    counts = {}
    body, counts["склеено переносов"] = join_hyphens(body)
    body, counts["убрано точечных выносок"] = strip_leaders(body)
    # Сборка идёт ДО НЕПОДВИЖНОСТИ, как и склейка переносов.  Причина та же
    # и такая же неприятная: возврат потерянного меняет текст, а
    # выравнивание блоков по абзацам смотрит вперёд на WINDOW абзацев, и
    # вернувшийся абзац сдвигает окно — на следующем проходе совпадает то,
    # что не совпало на этом.  Без этого цикла второй `books restructure`
    # давал другую книгу: на «Справочнике» появлялся заголовок
    # `## Ταβλυμα VII.1`, которого на первом прогоне не было.
    #
    # Счётчики разведены по смыслу: действия («возвращено…») складываются по
    # всем проходам, состояния (роли: глава, заголовок раздела) берутся с
    # последнего прохода.  На неподвижной точке все действия нулевые, так что
    # два способа счёта не спорят.
    lab = collections.Counter()
    first = None
    acted = collections.Counter()
    passes = 0
    while True:
        passes += 1
        new_body, lab = relabel(body, blks, suspect_pages=suspect,
                                have=_Index(_restore(body, kept)))
        # Склейку переносов повторяем ЗДЕСЬ ЖЕ.  Вернувшийся абзац может
        # кончаться переносом (`непе-`), и склеит его только следующий
        # `books restructure` — то есть шаг перестаёт быть идемпотентным не
        # на выравнивании, а на склейке.  Замер на «Огнеупорах»: 2 склейки и
        # 4 повторных возврата на втором запуске.
        new_body, nh = join_hyphens(new_body)
        counts["склеено переносов"] += nh
        new_body, nd = strip_leaders(new_body)
        counts["убрано точечных выносок"] += nd
        if first is None:
            first = lab
        for k, v in lab.items():
            if k.startswith(("возвращено", "колонцифр")):
                acted[k] += v
        if new_body == body or passes >= 5:
            body = new_body
            break
        body = new_body
    counts["проходов сборки структуры"] = passes
    if passes >= 5:
        print("  ВНИМАНИЕ: сборка структуры не сошлась за 5 проходов — "
              "книга на повторном запуске изменится")
    # Роли берём с ПЕРВОГО прохода: они описывают работу, проделанную над
    # книгой, какой она пришла.  С последнего прохода они описывали бы
    # доделки — «глава: 5» при восьми собранных главах в файле.
    lab = collections.Counter({k: v for k, v in (first or lab).items()
                               if not k.startswith(("возвращено",
                                                    "колонцифр"))})
    lab.update(acted)
    counts.update(lab)
    body, counts["пунктов перечня возвращено из заголовков"] = \
        unlist_headings(body)
    body, counts["подпись, а не заголовок (решётки снял рендер страницы)"] = \
        unhead_captions(body)
    dst = _restore(body, kept)
    if правленое is not None and правленое != dst:
        разница = sum(1 for a, b in zip(правленое.split("\n"), dst.split("\n"))
                      if a != b) + abs(правленое.count("\n") - dst.count("\n"))
        print(f"  ВНИМАНИЕ: книга на диске отличалась от собранной из слепка "
              f"на {разница} строк — эти строки перезаписаны. Прежняя книга "
              f"не сохранена; слепок цел: {os.path.basename(snap)}")
    open(book, "w", encoding="utf-8").write(dst)
    after = _measure(dst)

    # Покрытие метки — доля блоков, СЛИЧЁННЫХ с абзацем книги, и ничего
    # больше.  Прежняя редакция складывала роли: `глава * 2 + раздел верхнего
    # уровня` против числа блоков `header`, потому что на главу уходит два
    # блока — номер и название.  Складывались при этом роли, набранные из
    # РАЗНЫХ меток (главы приезжают и с `header`, и с `doc_title`, и с
    # `text`), и покрытие выходило 148%, 175%, 130%, 109%.  Величина, которая
    # может быть больше единицы, — не покрытие, а сумма непонятно чего; она
    # ещё и не может провалиться, то есть ни о чём не предупредит.
    #
    # Теперь счёт ведётся там, где происходит сличение (`_совпало:<метка>`), и
    # знаменатель тот же самый список блоков.  Доля по построению не
    # превосходит 100%, а роли, в которые превратились сличённые блоки,
    # печатаются отдельной таблицей — это разные вопросы.
    total = collections.Counter(l for l, *_ in blks)
    cover = {}
    for l, tot in total.items():
        if tot:
            cover[l] = (lab.get("_совпало:" + l, 0), tot)

    toc_path = p.toc
    name = os.path.basename(p.book)
    open(toc_path, "w", encoding="utf-8").write(toc(dst, name))

    # Служебные счётчики (с подчёркиванием) нужны только для сведения
    # покрытия и в отчёт не идут.
    counts = {k: v for k, v in counts.items() if not k.startswith("_")}
    for k, v in counts.items():
        print(f"  {k}: {v}")
    for k, (found, tot) in cover.items():
        print(f"  метка {k}: {found} из {tot} ({found/max(tot,1):.0%})")
    # Главы обязаны идти подряд от первой до последней.  Дыра в этом ряду —
    # единственный дешёвый способ заметить, что заголовок не собрался: сам по
    # себе «глав 28» выглядит как успех, пока не сравнить с 30.
    got = {n for m in re.findall(rf"^#+ (?:{_CW})\s+({_NUM})[.,]", dst, re.M | re.I)
           for n in [chapter_number(m)] if n is not None}
    seen = _chapter_numbers(blks)
    gap = sorted((set(range(1, max(seen or [0]) + 1)) - got)) if seen else []
    if not after["глав"] and after["заголовков всего"]:
        # «глав 0 из 0» читается как успех, а это провал: без номера главы
        # рушится и оглавление, и проверка порядка — каждый раздел считается
        # вставшим не на своё место.
        #
        # Диагноз ставится по json, а не наугад.  Первая редакция во всех
        # случаях советовала дописать слово в CHAPTER_WORDS — и врала дважды:
        # у книги с «ГЛАВА ПЕРВАЯ» слово в списке есть, а номер записан
        # словом; а у книги, где название главы пришло меткой
        # `paragraph_title`, код по json знает и слово, и номера, то есть
        # противоречил сам себе в соседних строках журнала.
        # Для диагноза смотрим блоки ЛЮБОЙ метки: беда как раз в том, что
        # название главы могло приехать не с той меткой, какую мы ждём.
        # `_chapter_numbers` для этого не годится — она нарочно смотрит только
        # заголовочные метки, чтобы прозаическое упоминание «см. главу 40» не
        # рисовало несобранных глав.
        marked = {n for _, c, *_x in blks
                  for m in [CHAPTER.match(c.strip())
                            or CHAPTER_FULL.match(c.strip())] if m
                  for n in [chapter_number(m.group(2))] if n is not None}
        if marked:
            print(f"  ВНИМАНИЕ: заголовков {after['заголовков всего']}, глав в "
                  f"разметке {len(marked)}, а собрано ни одной. Слово «глава» "
                  f"опознаётся — не сходится что-то другое: посмотри, какой "
                  f"меткой пришло название главы.")
        else:
            print(f"  ВНИМАНИЕ: заголовков {after['заголовков всего']}, а глав "
                  f"не опознано ни одной. Либо слово «глава» в этой книге не "
                  f"из списка CHAPTER_WORDS ({', '.join(CHAPTER_WORDS[:3])}, "
                  f"…), либо номер записан словом («ГЛАВА ПЕРВАЯ»), а шаблон "
                  f"ждёт цифру. Оглавление и проверка порядка недостоверны.")
    print(f"  глав {after['глав']} из {max(seen or [0])}"
          + (f", НЕ СОБРАНЫ: {gap}" if gap else "")
          + f", заголовков всего {after['заголовков всего']}"
          + f", порядок нарушен в {after['нарушений порядка разделов']} местах")
    after["глав не собрано"] = len(gap)
    print(f"оглавление: {toc_path}")
    print(f"целостность скана: {lstat}; дефектов {len(defects)}, "
          f"колонцифра прочитана неверно на {len(misread)} листах")
    for kind, page, val, why in defects:
        print(f"  ДЕФЕКТ СКАНА: {kind} — лист {page}: {why}")
    print(f"отчёт: {report(p.report, before, after, counts, cover, dst, name, layout.facts(p.outdir).get('passes'), (lstat, defects, misread), outdir=p.outdir)}")
    return 0


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(
        description="собрать книжную структуру в готовом разборе")
    ap.add_argument("outdir", help="каталог разбора (processed/<имя>)")
    a = ap.parse_args(argv)
    return restructure(a.outdir)


