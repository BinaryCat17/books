        f"- **Переносов не склеено {after['переносов не склеено']}.** "
        "Следующая строка начиналась не со строчной буквы, и склейка была бы "
        "догадкой.",
        "- **Диапазон последней главы доведён до конца файла.** Отличить "
        "указатель, глоссарий и послесловие от её собственных разделов "
        "разметка не позволяет, и угадывать мы не стали: в `toc.md` эта "
        "строка помечена. Значит, задняя часть книги входит в её диапазон — "
        "смотри по заголовкам ниже, где она начинается.",
