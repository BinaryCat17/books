# Зацикливание: общий прибор для Э2 (выбор основы) и Э3 (пометки).
#
# ДОГОВОР С Э2.  `looping(text)` — чистая функция без состояния и без чтения
# диска.  На вход даётся текст КАК ЕСТЬ, вместе с разметкой: снимает её сама
# функция, и оба этапа обязаны считать одинаково.  Возвращает None, если
# признаков нет, иначе словарь-улику: `chars` (знаков повтора, БЕЗ разметки),
# `kind` (`повтор` или `прогрессия`), `sample` (до 60 знаков звена).
# Э2 сравнивает страницы правилом «нет признаков → есть признаки», а при
# одинаковом исходе — по меньшему `chars`.  Порогов в Э2 своих не заводить:
# они здесь, в LOOP_*.
LOOP_MIN_TEXT = 1000        # знаков текста, короче — не смотрим вовсе
LOOP_MIN_REPEAT = 1000      # знаков подряд, состоящих из повтора сказанного
LOOP_MIN_PROGRESSION = 50   # членов арифметической прогрессии подряд
LOOP_SHINGLE = 30           # длина звена
LOOP_WINDOW = 200000        # окно просмотра: память не должна расти с книгой

_DIGITS = re.compile(r"\d+")


def bare(text):
    """Текст без разметки и без наших пометок — то, на чём считается повтор.

    Считать по разметке нельзя.  Замер на шести книгах (9 783 страницы трёх
    проходов, признак «повтор»): с тегами он срабатывает 534 раза, без тегов
    124, то есть 412 срабатываний из 534 — это `<td style='text-align:
    center; word-wrap: break-word;'>`, повторяющийся в НАСТОЯЩЕЙ таблице.
    Сумма «знаков повтора» завышается в 3.9 раза.
    """
    t = html.unescape(TAG.sub(" ", text)).replace("⚠", "").replace("≠", "")
    return _SPACES.sub(" ", t).strip()


def _repeat_run(t, k=LOOP_SHINGLE):
    """Длиннейший кусок подряд, целиком состоящий из уже сказанного.

    Окно нужно, чтобы память не росла с длиной входа: цикл повторяется
    вблизи себя, и окна в 200 тыс. знаков хватает с большим запасом — самый
    длинный найденный на шести книгах повтор 12 044 знака.
    """
    best, sample = 0, ""
    step = max(LOOP_WINDOW - LOOP_MIN_REPEAT, 1)
    for start in range(0, max(len(t) - k + 1, 1), step):
        chunk = t[start:start + LOOP_WINDOW]
        if len(chunk) <= k:
            break
        seen = set()
        cur = at = 0
        for i in range(len(chunk) - k + 1):
            sh = chunk[i:i + k]
            if sh in seen:
                if cur == 0:
                    at = i
                cur += 1
                if cur > best:
                    best, sample = cur, chunk[at:at + 60]
            else:
                seen.add(sh)
                cur = 0
    return (best + k - 1 if best else 0), sample


def _progression(t):
    """Длина самой длинной арифметической прогрессии подряд идущих чисел.

    Отдельный признак, потому что `1. 2. 3. … 841.` — это упор в потолок
    порождения, а не повтор: точный повторитель его не видит.  На шести
    книгах прогрессия — единственный признак ровно для одной страницы
    (`ogneupory` проход 3, стр. 0277: счёт `3 4 5 … 277` посреди таблицы).
    Одна из 125 — но эта одна не ловится ничем другим и не стоит ничего.
    """
    ns = [int(x) for x in _DIGITS.findall(t)[:5000]]
    best, i = 1, 0
    while i < len(ns) - 1:
        d = ns[i + 1] - ns[i]
        j = i + 1
        while j < len(ns) - 1 and ns[j + 1] - ns[j] == d:
            j += 1
        best = max(best, j - i + 1)
        i = j if j > i else i + 1
    return best


def looping(text):
    """Признаки зацикливания в куске текста.  None — чисто.

    Три признака, и все три считаются по тексту без разметки:
      * точный повтор 30-грамм — ловит `гггг…`, `. . . .`, повторённый абзац;
      * повтор с ДРЕЙФОМ звена (цифры сводятся к `#`) — ловит `2024年10月15日
        2024年10月16日 …`, 4 095 знаков китайских дат на титуле Стрелова, где
        точный повторитель видит только 1 064;
      * арифметическая прогрессия — ловит счёт до упора в потолок.

    Замер на шести книгах, 9 783 страницы трёх проходов: 125 срабатываний, из
    них ложных 0 — каждое проверено глазом, семь вдобавок по скану.  Порог
    длины отсекает 46 более коротких вырождений (300–999 знаков): они
    настоящие, но короче того, что стоит показывать.
    Сжимаемость gzip замерена и НЕ включена: все страницы с `gz <= 0.10`
    ловятся повтором, ни одной своей она не добавляет.
    """
    t = bare(text)
    if len(t) < LOOP_MIN_TEXT:
        return None
    exact, sample = _repeat_run(t)
    drift, dsample = _repeat_run(_DIGITS.sub("#", t))
    if drift > exact:
        exact, sample = drift, dsample
    if exact >= LOOP_MIN_REPEAT:
        return {"kind": "повтор", "chars": exact, "sample": sample}
    prog = _progression(t)
    if prog >= LOOP_MIN_PROGRESSION:
        return {"kind": "прогрессия", "chars": prog, "sample": t[:60]}
    return None


def looped(md):
    """Да/нет для выбора основы.  Признаки — те же и только те, что в `looping`."""
    return looping(md) is not None


def looping_pages(pass_root):
    """Страницы прохода с признаками зацикливания — (имя, улика).

    Тот же прибор, только развёрнутый на каталог.  Э2 берёт его же, чтобы
    выбирать основу постранично; здесь он нужен, чтобы прогон СКАЗАЛ, сколько
    страниц основы испорчено, а не молчал об этом.
    """
    out = []
    for f in sorted(glob.glob(os.path.join(pass_root, "pages", "*.md"))):
        try:
            hit = looping(open(f, encoding="utf-8").read())
        except OSError:
            continue
        if hit:
            out.append((os.path.basename(f)[:-3], hit))
    return out


