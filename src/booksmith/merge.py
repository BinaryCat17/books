"""Свод нескольких проходов в одну книгу с пометками неустойчивости.

Основа собирается ПОСТРАНИЧНО: для каждой страницы берётся то чтение, которое
не зациклилось, не порвало лестницу номеров строк и вернуло больше непустых
ячеек; при равенстве — первый проход, жадный.  Остальные чтения этой же
страницы становятся её свидетелями: ячейка, прочитанная всеми одинаково,
надёжна; разошедшаяся — нет.

Раньше основой всегда был проход 1 целиком, а два других служили только
детекторами.  Замер по шести книгам: 32 685 непустых ячеек у прохода 1 против
40 109 у оракула «взять лучшую страницу» — мимо книги шло 22.7% оплаченного.

Пометки в итоге две, и они про разное:
  ⚠  модель сама не была уверена (по вероятностям токенов);
  ≠  чтения разошлись (модель гадала, но уверенно).
Первый признак ловит искажённый текст, второй — правдоподобную выдумку.
"""
import collections, difflib, glob, html, os, re, shutil, unicodedata

from . import layout

TAG = re.compile(r"<[^>]+>")
CELL = re.compile(r"(<t[dh][^>]*>)(.*?)(</t[dh]>)", re.I | re.S)
TABLE = re.compile(r"<table\b.*?</table>", re.I | re.S)
ROW = re.compile(r"<tr[^>]*>.*?</tr>", re.I | re.S)
CELL_MARK = "чтения разошлись"


def plain(c):
    return html.unescape(TAG.sub("", c)).replace("⚠", "").replace("≠", "").strip()


# Ступени «двойники кириллица/латиница» здесь НЕТ, и это решение, а не
# упущение.  Она сводила `М` к `M`, `Х` к `X` и снимала 64 пометки «вред 0» —
# но мера вреда была не та.  Подмена двойника в этом корпусе есть САМА ОШИБКА
# распознавания, а не разнопись: на скане «Благородная шпинель, MgO·Al₂O₃», в
# книге «МгО·А₁₂O₃»; на скане «Х10Л6», в книге «X10A6».  Ступень гасила ровно
# тот класс, который пометка обязана ловить.
#
# Замер против ручной разметки (29 дефектов, шесть собранных книг):
#
#     со ступенью    пометок 6 714    найдено 14 из 29    лифт 2.70
#     БЕЗ ступени    пометок 6 786    найдено 16 из 29    лифт 3.06
#
# Лишние 72 пометки покупают два дефекта — 2.8% на пометку против 0.21% у уже
# стоящих.  Прибор от снятия ступени стал острее, а не шумнее.
_SPACES = re.compile(r"\s+")
_DASHES = re.compile(r"[‐‑‒–—―−˗－]")
_DECIMAL = re.compile(r"(?<=\d),(?=\d)")
_TAIL = re.compile(r"[\s\W_]+$", re.UNICODE)


def cell_key(v):
    """Ключ ячейки: под каким именем два чтения считаются одним и тем же.

    Ступени и их цена замерены на шести книгах (32 634 ячейки основы, 7 101
    пометка до правки).  Польза — снятых пометок; вред — случаев, когда
    пометка снята мнимым согласием, то есть ключ совпал у РАЗНЫХ величин::

        NFKC и пробелы          снято  127   вред 0
        регистр                 снято   90   вред 0
        тире/дефис/минус        снято  376   вред 0
        десятичная запятая      снято   42   вред 0
        ХВОСТОВАЯ пунктуация    снято  147   вред 0
        --- граница -------------------------------
        ГОЛОВНАЯ пунктуация     снято  139   вред 4     `.850` == `850`
        вся пунктуация          снято  504   вред 108   `6—2` == `6,2`

    Граница проходит по хвостовой пунктуации, и это замер, а не вкус.  Снос
    ведущей точки запрещён по той же причине, по которой она включена в
    шаблон `NUM`: в этой предметной области `.850` — это 0,850, а не 850.
    Снос всей пунктуации слипает 897 групп значений (2 233 ложных слияния).
    """
    v = _SPACES.sub(" ", unicodedata.normalize("NFKC", v)).strip().casefold()
    v = _DECIMAL.sub(".", _DASHES.sub("-", v))
    return _TAIL.sub("", v) or v


def cells_of_text(md):
    """Ключи всех непустых ячеек текста — множеством, а не мультимножеством."""
    return {cell_key(plain(body))
            for t in TABLE.finditer(md)
            for _, body, _ in CELL.findall(t.group(0))
            if plain(body)}


def rows_of_text(md):
    """Строки таблиц: список значений ячеек, по строке за раз."""
    for t in TABLE.finditer(md):
        for r in ROW.finditer(t.group(0)):
            yield [plain(b) for _, b, _ in CELL.findall(r.group(0))]


def row_label(cells):
    """Первое непустое значение строки — по нему строки и сличаются."""
    for c in cells:
        if c:
            return cell_key(c)
    return None


# Число целиком, вместе с ведущей точкой: в этой предметной области `.0005`
# пишут и так, и как `0.0005`, и без ведущей точки шаблон превращал одно
# написание в другое в мнимое расхождение — из 41 первой пометки таких было
# больше половины.  Хвостовая пунктуация в число не входит: `26.30,` — это
# число и запятая, а не число с запятой.
#
# Ведущая точка засчитывается, только если перед ней НЕ буква: иначе точка от
# «Sec.» прилипает к номеру раздела, и `Sec. 27.35` против `Sec.27.35`
# объявляется расхождением чисел, хотя различие в пробеле.
NUM = re.compile(r"(?<![^\W\d_])\.?\d+(?:[.,]\d+)*")
# Формулы LaTeX: внутрь них не заходим вовсе.  Замер на курсе физики: токены
# формул расходятся между чтениями на 38-40%, то есть почти всегда, а пометка
# внутри `$…$` вдобавок ломает саму формулу — `\sqrt{<mark>0.0049</mark>…}`
# перестаёт быть формулой.  Расхождения в математике надо ловить иначе, и это
# отдельная работа.
# Одиночные `$…$` считаем формулой, только если внутри есть знаки формулы:
# иначе «цена $5.00 за 12 шт, всего $7.00» целиком объявляется математикой, и
# настоящее расхождение внутри неё пропадает.
MATH = re.compile(r"\$\$.*?\$\$|\$[^$\n]*[\\^_{}][^$\n]*\$", re.S)
PROSE_MARK = "чтения разошлись"
ALREADY = re.compile(r'<mark title="' + PROSE_MARK)


def _paragraphs(md):
    """Абзацы страницы без таблиц.

    Таблицы вырезаются целиком: их ячейки сличаются отдельно и точнее, по
    содержимому, а не по месту.
    """
    body = TABLE.sub(lambda m: "\x00", md)
    return re.split(r"(\n\s*\n)", body)


def _key(p):
    """Ключ абзаца для сопоставления: только буквы и цифры, без регистра."""
    return re.sub(r"[\W_]+", " ", TAG.sub(" ", p), flags=re.UNICODE).strip().casefold()


def _same_number(a, b):
    """Одно ли это число, записанное по-разному.

    `.001` и `0.001` — одно и то же; `.001` и `.0001` — разное.  Запятая и
    точка тоже одно: в русской книге распознаватель пишет разделитель то так,
    то этак, и без этой поправки на курсе физики семь пометок из двадцати были
    мнимыми — ровно смена написания.
    """
    def n(x):
        x = x.replace(",", ".")      # `0,5` и `0.5` — одно число
        return x.lstrip("0") if x[:2] == "0." else x
    return n(a) == n(b)


def _numbers(text):
    """Числа в тексте — со смещениями, минуя разметку.

    Внутрь тегов не заходим: в `<img src="...0091_1011...">` цифр больше, чем
    во всей странице, и все они к содержанию отношения не имеют.
    """
    holes = [(m.start(), m.end()) for m in TAG.finditer(text)]
    holes += [(m.start(), m.end()) for m in MATH.finditer(text)]
    out = []
    for m in NUM.finditer(text):
        if any(a <= m.start() < b for a, b in holes):
            continue
        # Числа, липнущие к знакам LaTeX, пропускаем даже вне `$…$`:
        # надстрочник `10^{14}` распадается у одного чтения в `1014`, у
        # другого в `10` и `14`, и свод объявляет расхождением развал
        # разметки, а не расхождение величины.
        near = text[max(0, m.start() - 1):m.start()] + text[m.end():m.end() + 1]
        if set(near) & set("^_{}\\"):
            continue
        val = m.group(0).rstrip(".,")
        out.append((m.start(), m.start() + len(val), val))
    return out


def mark_prose(base_md, witness_mds):
    """Пометить числа прозы, в которых чтения разошлись.

    Зачем это вообще: до сих пор свод сличал ТОЛЬКО ячейки таблиц, а проза
    первого прохода копировалась в итог побайтово.  Замер показал цену такой
    экономии — в справочнике по станкам 0.29% знаков книги лежит в ячейках, то
    есть проверялось три сотых доли текста, а в прозе оставались 69
    неподтверждённых чисел на сорока страницах: допуски вида `.001` против
    `.0001` и ссылки `Sec. 18.7` против `13.7`.  Ровно та правдоподобная
    выдумка, которую вероятности токенов не ловят по определению — модель в
    ней уверена.

    Сличаются ЧИСЛА, а не слова.  Пословное сличение годится для прозы
    справочника (0.29% помеченных слов, медиана ноль на страницу), но на книге
    с формулами превращается в шум: у Фейнмана расходится 6.9% слов, а токены
    LaTeX — на 38-40%.  Числа же дают 69 и 90 пометок на всю книгу
    соответственно, без шума вовсе, и это именно то, чего нельзя чинить на
    глаз.

    В подпись пометки кладутся варианты свидетелей.  Это улика, а не подсказка
    к исправлению: правило «числа только помечать, никогда не восстанавливать»
    остаётся, но человеку, идущему сверять со сканом, полезно знать, что
    прочли другие проходы.
    """
    base = _paragraphs(base_md)
    wits = [_paragraphs(w) for w in witness_mds]
    if not wits:
        # Свидетелей нет вовсе — об этом сказано один раз, отдельной строкой.
        # Считать при этом каждую страницу «несверенной» бессмысленно: это не
        # свойство страницы, а свойство прогона.
        return base_md, 0, 0

    # Абзацы сопоставляем, а не приравниваем по номеру.  Требование «одинаковое
    # число абзацев» оставляло несверенными 117 страниц из 539: проходы делят
    # текст по-разному (на стр. 0002 первый дал 35 абзацев, второй 19), и это
    # не разметка, а настоящее расхождение дробления.  Сличаем только те
    # абзацы, которые сошлись у ВСЕХ свидетелей однозначно; остальные считаем
    # несверенными и говорим об этом числом.
    def _pair(a, b):
        ka = [_key(x) for x in a]
        kb = [_key(x) for x in b]
        out = {}
        for op, i1, i2, j1, j2 in difflib.SequenceMatcher(
                None, ka, kb, autojunk=False).get_opcodes():
            # `equal` — якоря, `replace` равной длины — то, ради чего всё и
            # затевалось: абзацы соответствуют друг другу, но ОТЛИЧАЮТСЯ.
            #
            # Первая редакция брала только `equal`, и это была ошибка по
            # существу: сопоставление по равенству исключает ровно те абзацы,
            # где чтения разошлись.  Замер поймал сразу — пометок стало 2
            # вместо 30.
            if op == "equal" or (op == "replace" and i2 - i1 == j2 - j1):
                for d in range(i2 - i1):
                    out[i1 + d] = j1 + d
        return out

    pairs = [_pair(base, w) for w in wits]
    # Согласие ХОТЬ ОДНОГО свидетеля, а не всех.  Прежнее пересечение
    # (`aligned &= set(p)`) устроено так, что счёт слепых абзацев растёт с
    # числом свидетелей ПО ПОСТРОЕНИЮ: каждый новый свидетель может только
    # вычесть из множества сверенных.  Замер это и показывал — book-new
    # 39/44/67 слепых при одном, двух, трёх свидетелях, feynman 10/19/22.
    # Получалось, что третье купленное чтение УХУДШАЛО отчёт.  Абзац,
    # сошедшийся хотя бы с одним чтением, сверен этим чтением; остальные для
    # него просто молчат, и сличаются только те, кто сошёлся.
    aligned = set()
    for p in pairs:
        aligned |= set(p)

    marked = 0
    blind = 0
    out = list(base)
    for i, part in enumerate(base):
        if i % 2 or "\x00" in part or not part.strip():
            continue
        if part.rstrip().endswith("≠"):
            # Абзац уже помечен прошлым сведением: второй свод по тем же
            # каталогам не должен дописывать знак второй и третий раз.
            continue
        bn = _numbers(part)
        if not bn:
            # База чисел не видит, а свидетель видит — число пропало при
            # чтении.  Это ровно та потеря, которую иначе не заметить: искать
            # нечего, потому что искомого в тексте нет.
            if i in aligned and any(_numbers(w[p[i]])
                                    for w, p in zip(wits, pairs) if i in p):
                out[i] = part.rstrip() + " ≠"
                marked += 1
            continue
        if i not in aligned:
            # Абзац не сошёлся ни с одним свидетелем — числа в нём не
            # проверены никем, и это надо назвать, а не замолчать.
            blind += 1
            continue
        # Только те свидетели, у которых этот абзац нашёлся: остальные о нём
        # ничего не говорят, и молчание нельзя читать ни как согласие, ни как
        # расхождение.
        wn = [_numbers(w[p[i]]) for w, p in zip(wits, pairs) if i in p]
        if any(len(x) != len(bn) for x in wn):
            # Состав чисел разошёлся — метим абзац целиком, поштучно тут
            # сопоставлять уже нечем.
            # Видимая пометка, а не HTML-комментарий.  Первая редакция ставила
            # комментарий, и в нём тонули три четверти всех пометок: в html,
            # epub и pdf он не виден вовсе, а среди спрятанного были настоящие
            # расхождения цифр.  `≠` — тот же знак, что и в ячейках таблиц, и
            # он уже описан в work_instruction.md.
            out[i] = part.rstrip() + " ≠"
            marked += 1
            continue
        new = part
        decayed = False
        for k in range(len(bn) - 1, -1, -1):
            a, b, val = bn[k]
            alt = sorted({x[k][2] for x in wn
                          if not _same_number(x[k][2], val)})
            if not alt:
                continue
            # Развал разметки не выдаём за расхождение величины.  Надстрочник
            # `10^{14}` у одного чтения слипается в `1014`, у другого
            # рассыпается на `10` и `14`; называть это «прочли 1014 против 10»
            # значит врать читателю.  Признак: одно число — начало другого, и
            # длина разошлась больше чем на знак.  Абзац пометку всё равно
            # получит, но по составу чисел, а не поимённо.
            if all((val.startswith(x) or x.startswith(val))
                   and abs(len(val) - len(x)) >= 2 for x in alt):
                decayed = True
                continue
            # Число считаем всегда, а оборачиваем только неотмеченное: если
            # исключить помеченные из подсчёта, при повторном сведении состав
            # чисел разойдётся сам с собой и абзац получит лишнее `≠`.
            if any(m.start() < a and (new.find("</mark>", m.end()) + 7) > b
                   for m in ALREADY.finditer(new)):
                continue
            new = (new[:a] + f'<mark title="{PROSE_MARK}: {", ".join(alt)}">'
                   + new[a:b] + "</mark>" + new[b:])
            marked += 1
        if decayed:
            # Пометка ставится независимо от того, были ли в абзаце поимённые:
            # прежнее условие `new is part` молча теряло сведение о развале
            # разметки, если рядом нашлось названное расхождение.
            new = new.rstrip() + " ≠"
            marked += 1
        out[i] = new

    if not marked:
        return base_md, 0, blind
    # Собираем обратно, вернув таблицы на место — разрезав по заглушке и
    # переложив куски.  Регулярная замена здесь была ошибкой дважды: при
    # вызываемой замене `re.sub` не разбирает экранирование, и обратные слэши в
    # таблицах удваивались, а лишняя заглушка в тексте роняла весь свод
    # `StopIteration`, оставляя каталог полусведённым.  Разрез ничего не
    # экранирует и не падает: лишний кусок просто остаётся как был.
    tables = TABLE.findall(base_md)
    parts = "".join(out).split("\x00")
    res = parts[0]
    for n, tail in enumerate(parts[1:]):
        res += (tables[n] if n < len(tables) else "\x00") + tail
    return res, marked, blind


def _witness_index(md):
    """Свидетель для сличения ячеек: множество ключей и строки по метке."""
    rows = collections.defaultdict(list)
    for cs in rows_of_text(md):
        l = row_label(cs)
        if l is not None:
            rows[l].append(cs)
    return cells_of_text(md), rows


def _witness_values(wit, label, i, width):
    """Что свидетели держат на ЭТОМ месте строки с такой меткой.

    Возвращает множество значений или None, если места нет либо одноимённые
    строки самого свидетеля расходятся между собой.  Второе — не придирка:
    метка строки в книге не уникальна (`Всего`, `в млн. м`), и без этой
    проверки одноимённая строка из другой таблицы подсовывает чужое число.
    Замер: без проверки правило метит 401 пустую ячейку, с проверкой 288.
    """
    out = set()
    for _, rows in wit:
        same = [r for r in rows.get(label, ()) if len(r) == width]
        vals = {r[i] for r in same if r[i]}
        if len({cell_key(v) for v in vals}) > 1:
            return None
        out |= vals
    return out


def _with_title(tag, alt):
    """Дописать в открывающий тег ячейки варианты свидетелей.

    Это улика, а не подсказка к исправлению: правило «числа только помечать,
    никогда не восстанавливать» остаётся.  Но `≠` без вариантов нем — человек
    видит, что чтения разошлись, и не видит, на чём.
    """
    if not alt or 'title="' in tag:
        return tag
    say = html.escape(", ".join(sorted(alt))[:200], quote=True)
    return tag[:-1] + f' title="{CELL_MARK}: {say}">'


def mark_cells(text, witnesses):
    """Пометить `≠` ячейки, которых нет у всех свидетелей.

    Счёт по всей книге, а не по странице: в книжном файле границ страниц уже
    нет, а таблицы, разорванные разрывом страницы, склеены — пересборка из
    страниц это теряла.  Огрубление безопасное: оно может лишь НЕ заметить
    расхождение, но не выдумать его.

    Сличается МНОЖЕСТВО значений, а не мультимножество.  Прежнее `w[v] >= k`
    требовало, чтобы значение встречалось у свидетеля не реже, чем у основы, и
    метило вторую `0,5` в столбце только за то, что она вторая.  Замер: из
    7 101 пометки 1 490 (21%) были ровно этим — артефактом кратности.  Потеря
    от огрубления честная и названа: если основа повторила значение лишний
    раз, свод этого больше не заметит; но кратность в таблице и не сличается —
    места у ячеек нет, только содержимое.

    Пустая ячейка тоже считается и тоже метится.  Прежний выход `if not v`
    стоял ДО `total`, и 3 077 ячеек (8.6% в 312 таблицах из 943) не попадали
    ни в знаменатель, ни под пометку — то есть потерянное значение выглядело
    как проверенная пустота.  Пометить пустоту по содержимому нельзя, поэтому
    для неё (и только для неё) строка сличается по месту: метка строки плюс
    номер ячейки при совпавшей ширине.
    """
    wit = [_witness_index(w) for w in witnesses]
    marked = total = empty = 0

    def one_row(r):
        nonlocal marked, total, empty
        cells = [plain(b) for _, b, _ in CELL.findall(r)]
        label = row_label(cells)
        width = len(cells)
        seat = [-1]

        def one(m):
            nonlocal marked, total, empty
            seat[0] += 1
            i = seat[0]
            v = plain(m.group(2))
            total += 1
            if m.group(2).rstrip().endswith("≠"):
                # Уже помечено прошлым сведением — второй свод по тем же
                # каталогам не дописывает знак второй и третий раз.
                marked += 1
                if not v:
                    empty += 1
                return m.group(0)
            if not v:
                empty += 1
                if label is None:
                    return m.group(0)
                alt = _witness_values(wit, label, i, width)
                if not alt:
                    return m.group(0)
                marked += 1
                return (_with_title(m.group(1), alt) + m.group(2) + " ≠"
                        + m.group(3))
            k = cell_key(v)
            if all(k in keys for keys, _ in wit):
                return m.group(0)
            marked += 1
            alt = _witness_values(wit, label, i, width) if label else None
            alt = {x for x in (alt or ()) if cell_key(x) != k}
            return (_with_title(m.group(1), alt) + m.group(2) + " ≠"
                    + m.group(3))

        return CELL.sub(one, r)

    def one_table(t):
        # Куски между строками прогоняются тем же ходом: ячейка вне `<tr>` —
        # редкость, но молча не считать её значит врать знаменателю.
        out, prev = [], 0
        for r in ROW.finditer(t):
            out.append(one_row(t[prev:r.start()]))
            out.append(one_row(r.group(0)))
            prev = r.end()
        out.append(one_row(t[prev:]))
        return "".join(out)

    out, prev = [], 0
    for t in TABLE.finditer(text):
        out.append(text[prev:t.start()])
        out.append(one_table(t.group(0)))
        prev = t.end()
    out.append(text[prev:])
    return "".join(out), marked, total, empty


