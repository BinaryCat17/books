# выбран замером, а не на глаз: без него (0.0) книга получает 39 691 ячейку,
# но теряет 11 046 слов — выигрывают усечённые страницы, ровно та беда, из-за
# которой «меньше всего мусора» негодно как критерий.  При 1.0 ячеек 39 342.
# 0.90 — 39 580 ячеек и +2 747 слов к проходу 1.
KEEP_WORDS = 0.90
# Если основа сама зациклилась, её слова считать не с чем: 4096 токенов
# `μ/μ/μ/…` это тоже «слова».  Порог для такой страницы отдельный и мягкий.
# Замер по шести книгам, знаков на зацикленных страницах итога: при 0.9 их
# 99 441, при 0.5 — 71 060, при 0.1 — 32 090, но слов тогда 990 275, меньше
# чем у прохода 1 (995 504), то есть книга беднеет.  0.5 — последняя точка,
# где слов больше, чем было.
KEEP_WORDS_LOOP = 0.50
SYNC_SLACK = 300         # насколько далеко вперёд ищем строку при разметке


ROW_BODY = re.compile(r"<tr[^>]*>(.*?)</tr>", re.I | re.S)
SPAN = re.compile(r"<(t[dh])([^>]*)>(.*?)</\1>", re.I | re.S)
INT_CELL = re.compile(r"^\d{1,3}$")


def _span(attrs, name):
    m = re.search(name + r'\s*=\s*"?(\d+)', attrs, re.I)
    return int(m.group(1)) if m else 1


def _grid(t):
    """Сетка таблицы с раскрытыми rowspan/colspan."""
    g, busy = [], set()
    for r, body in enumerate(ROW_BODY.findall(t)):
        while len(g) <= r:
            g.append({})
        c = 0
        for _, at, val in SPAN.findall(body):
            while (r, c) in busy:
                c += 1
            rs, cs = _span(at, "rowspan"), _span(at, "colspan")
            v = plain(val)
            for dr in range(rs):
                while len(g) <= r + dr:
                    g.append({})
                for dc in range(cs):
                    if dr or dc:
                        busy.add((r + dr, c + dc))
                    g[r + dr][c + dc] = v if not dr else ""
            c += cs
    w = max((max(d) + 1 if d else 0) for d in g) if g else 0
    return [[d.get(i, "") for i in range(w)] for d in g]


def ladder(md):
    """Высота лестниц номеров строк на странице — проверка целостности.

    Справочная таблица часто нумерует строки: «Номер режима по рис. 1.54» —
    1, 2, 3 … 8.  Ряд номеров монотонен по построению, как колонцифры для
    скана: если чтение потеряло строку или сдвинуло значения, ряд рвётся.
    Число ячеек этого не видит: чтение, съевшее строку, теряет три ячейки из
    полусотни, а чтение, склеившее описания в одну ячейку, теряет семь — и по
    ячейкам проигрывает, хотя номера у него целы.

    Ровно это случилось с таблицей режимов термообработки чугуна (стр. 0089,
    вырезка `imgs/tbl_p0089_177_245_1460_2192.jpg`): проход 1 дал 55 ячеек и
    лестницу 1..7, сдвинув значения на строку вниз у семи режимов из восьми;
    проход 2 дал 40 ячеек и целую лестницу 1..8 с верной привязкой значений.

    Признак редкий и потому дешёвый: на 3268 страницах шести книг он меняет
    выбор ОДИН раз, ценой 15 ячеек из 37 тысяч.
    """
    tot = 0
    for m in TABLE.finditer(md):
        g = _grid(m.group(0))
        best = 0
        w = max((len(r) for r in g), default=0)
        for c in range(w):
            want, n = 1, 0
            for row in g:
                v = row[c] if c < len(row) else ""
                if not v:
                    continue
                if INT_CELL.match(v):
                    k = int(v)
                    if k == want:
                        n += 1
                        want += 1
                    elif k > want:
                        break
            best = max(best, n)
        if best >= 4:
            tot += best
    return tot


def cells_count(md):
    """Непустых ячеек в тексте."""
    n = 0
    for t in TABLE.finditer(md):
        for _, body, _ in CELL.findall(t.group(0)):
            if plain(body):
                n += 1
    return n


def words_count(md):
    """Слов на странице ВМЕСТЕ с содержимым ячеек.

    Считать слова только вне таблиц (`prose_words`) для этой охраны нельзя, и
    это не мелочь: у «Кристаллизации» на стр. 0144 проход 1 прочёл 2 слова и
    ни одной таблицы, а проход 2 — таблицу в 822 ячейки.  Прозы у свидетеля
    стало 0 из 2, охрана по прозе его отвергала, и 822 оплаченные ячейки
    оставались в черновике.  Текст, переехавший из абзаца в ячейку, — это
    выигрыш, а не потеря.
    """
    return len(re.findall(r"[^\W\d_]+", TAG.sub(" ", md), re.UNICODE))


def prose_words(md):
    """Слов вне таблиц."""
    return len(re.findall(r"[^\W\d_]+", TAG.sub(" ", TABLE.sub(" ", md)),
                          re.UNICODE))


HEAD_LEVEL = re.compile(r"^#+\s+")
MARK_TAG = re.compile(r"</?mark(?:\s[^>]*)?>")
IMG_SRC = re.compile(r'src="(imgs/[^"]+)"')
TBL_SCAN = re.compile(r"<!-- скан таблицы: (imgs/[^ ]+) -->")


def _sync_key(l):
    """Строка для разметки книги по страницам.

    Уровень заголовка и пометки ⚠ из счёта убраны: `restructure_pages`
    перенумеровывает `#` (у «Биохимии» 876 строк на 776 страниц), а
    `_mark_uncertain` кладёт `<mark>` в книгу и в страницы порознь.  Ни то, ни
    другое не сдвигает содержания, и если сличать как есть, граница страницы
    объявляется потерянной там, где она цела.
    """
    return MARK_TAG.sub("", HEAD_LEVEL.sub("# ", l.strip()))


def page_spans(page_texts, book):
    """Где в книге прохода лежит каждая его страница и цела ли граница.

    Книга прохода — это его же страницы, но со сшитыми через разрыв таблицами
    (`restructure_pages(merge_tables=True)` на арендованной машине) и
    перенумерованными уровнями заголовков.  Сшивка уничтожает границу
    страницы: половины таблицы больше не разделить, и заменять такую страницу
    чужим чтением нельзя — вышла бы таблица, склеенная из двух разных книг.

    Возвращает `(cuts, clean, lines)`: `cuts[i]` — строка книги, с которой
    начинается страница i (`cuts[n]` — конец), `clean[i]` — можно ли вынуть
    страницу целиком.  Разрезы покрывают книгу без пропусков и нахлёстов:
    склеенные обратно, они дают её байт в байт — это проверено на всех шести
    книгах и это то, что делает правку безопасной: страница, которую никто не
    заменил, доходит до читателя такой же, как раньше.

    Считается за один проход по якорям, без `difflib`: полное сличение
    30 тысяч строк шести книг стоит десять минут, синхронизация — полсекунды,
    и даёт тот же ответ до страницы (69 несменяемых страниц из 3268 обоими
    способами, поимённо те же).
    """
    lines, bounds = [], []
    for t in page_texts:
        a = len(lines)
        lines.extend(t.splitlines(keepends=True))
        bounds.append((a, len(lines)))
    blines = book.splitlines(keepends=True)
    idx = collections.defaultdict(collections.deque)
    for j, l in enumerate(blines):
        k = _sync_key(l)
        if k:
            idx[k].append(j)

    at = [None] * len(lines)
    cur = 0
    for i, l in enumerate(lines):
        k = _sync_key(l)
        q = idx.get(k) if k else None
        if not q:
            continue
        while q and q[0] < cur:
            q.popleft()
        if q and q[0] - cur <= SYNC_SLACK:
            at[i] = q[0]
            cur = q[0] + 1
            q.popleft()

    n = len(page_texts)
    first = [None] * n
    last = [None] * n
    fidx = [None] * n
    lidx = [None] * n
    for i, (a, b) in enumerate(bounds):
        for k in range(a, b):
            if at[k] is None:
                continue
            if first[i] is None:
                first[i], fidx[i] = at[k], k
            last[i], lidx[i] = at[k], k

    cuts = [0] * (n + 1)
    cuts[n] = len(blines)
    pos = 0
    for i in range(n):
        cuts[i] = first[i] if first[i] is not None and first[i] >= pos else pos
        pos = cuts[i]
    for i in range(n - 1, -1, -1):
        cuts[i] = min(cuts[i], cuts[i + 1])
    # Первая страница начинается с начала книги, чем бы она ни начиналась.
    # Без этой строки первая строка книги пропадала, если она не пришилась к
    # странице: у «Огнеупоров» книга собиралась на один байт короче исходной,
    # и заметила это только приёмка «разрезы дают книгу байт в байт».
    cuts[0] = 0

    clean = [False] * n
    for i, (a, b) in enumerate(bounds):
        if first[i] is None:
            continue
        clean[i] = (
            all(at[k] is not None or not lines[k].strip()
                for k in range(a, fidx[i] + 1))
            and all(at[k] is not None or not lines[k].strip()
                    for k in range(lidx[i], b))
            and all(not blines[j].strip() for j in range(cuts[i], first[i]))
            and all(not blines[j].strip()
                    for j in range(last[i] + 1, cuts[i + 1])))
    return cuts, clean, blines


def _pages_by_name(pass_root):
    out = {}
    for f in sorted(glob.glob(os.path.join(pass_root, "pages", "*.md"))):
        out[os.path.basename(f)[:-3]] = f
    return out


def _refs(md):
    return {os.path.basename(x)
            for x in IMG_SRC.findall(md) + TBL_SCAN.findall(md)}


def drop_lost_scans(md, have):
    """Обезвредить ссылки на вырезки таблиц, которых нет на диске.

    Вырезка — это улика, а не содержимое: по ней сверяют числа со сканом.
    Свидетели четырёх книг из шести приехали без картинок вовсе
    (`cli.py:162`, `pull_exclude` вымел `pages/*.json` и `imgs/` заодно), и
    страница свидетеля ссылается на вырезку, которой на диске нет.

    Выбрасывать из-за этого саму таблицу нельзя: замер по шести книгам —
    47 страниц, 5 149 непустых ячеек, семь десятых всей прибавки свода.  Но и
    молчать нельзя: ссылка, ведущая в никуда, хуже её отсутствия.  Поэтому
    комментарий переписывается так, чтобы он перестал быть ссылкой и назвал
    пропажу поимённо.  `structure.py` ищет ровно `скан таблицы:` и такую
    строку больше не засчитывает — таблица честно числится без вырезки.
    """
    n = [0]

    def one(m):
        name = os.path.basename(m.group(1))
        if name in have:
            return m.group(0)
        n[0] += 1
        return f"<!-- вырезка таблицы не выгружена: {name} -->"

    return TBL_SCAN.sub(one, md), n[0]



# --------------------------------------------- у какого прохода взята страница
#
# Э4 показал, чего стоит это умолчание.  `structure.py` берёт метки структуры
# из `passes/1/pages/*.json` — всегда, для любой страницы.  После Э2 основа
# собирается постранично, и на странице, взятой у прохода 2, блок прохода 1 в
# книге отсутствует: не потому, что потерян, а потому, что то же место
# написано словами другого чтения.  Шаг возврата считает его потерянным и
# ставит абзац вторым — в двух редакциях подряд.  Замер на шести книгах: 362
# возвращённых блока вместо 78, из них 284 задвоения.
#
# Э4 обошёлся местной заплатой — сходством с соседями (`_already_here`), — и
# честно назвал её заплатой: «правильное решение — чтобы merge записывал, у
# какого прохода взята каждая страница».  Вот запись.
#
# Формат нарочно скучный: `{"0271": 2}` — номер листа строкой, номер прохода
# числом от 1.  Строкой потому, что json всё равно сделает ключ строкой, и
# лучше пусть это будет видно в файле, чем выяснится при чтении.


def remember_base(outdir, by_page, note=None):
    """Записать в run.json, у какого прохода взята каждая страница."""
    d = {"основа по страницам": {str(k): int(v) for k, v in by_page.items()}}
    if note:
        d["основа по страницам: как выбрана"] = note
    layout.remember(outdir, **d)
    сколько = collections.Counter(by_page.values())
    print("основа по страницам записана в run.json: "
          + ", ".join(f"проход {k} — {v} стр." for k, v in sorted(сколько.items())))
    return d

def choose_base(passes, imgs_top):
    """Собрать основу постранично и свидетелей — из непринятых чтений.

    Возвращает `(текст, [свидетели], сведения)` либо None, если выбирать не из
    чего и надо идти прежним путём.

    Порядок предпочтения, по убыванию:

    1. **Не зациклено.**  Зацикленная страница выбрасывается независимо от
       того, сколько в ней ячеек: 4096 токенов, набитых `μ/μ/μ/…`, это не
       данные.  Первым критерием, а не последним, потому что «меньше всего
       мусора» само по себе негодно — усечённая страница выигрывает.
    2. **Целее лестница номеров строк** (см. `ladder`).  Срабатывает на одной
       странице из 3268 — зато на той, где чтение с бо́льшим числом ячеек
       сдвинуло значения на строку.
    3. **Больше непустых ячеек.**  Главный источник прибавки.  На странице без
       таблиц у всех чтений ноль, и критерий молчит по построению: страница
       без таблиц заменяется только по пункту 1.
    4. **Проход 1 при равенстве.**  Он жадный (temperature 0), свидетели
       читаны при 0.4; при прочих равных берётся более надёжное чтение.

    Кандидаты перебираются по этому порядку, и каждого проверяют три охраны;
    не прошёл — берётся следующий, а если не прошёл никто — проход 1:

    * **сшивка.**  Страница, чью границу уничтожила сшивка таблицы через
      разрыв, не заменяется вовсе (`page_spans`).  У «Справочника» таких
      55 страниц из 760, у «Биохимии» 8 из 776, у остальных 0–3;
    * **слова.**  Свидетель обязан сохранить `KEEP_WORDS` слов страницы
      (вместе с ячейками): усечённая страница даёт полную таблицу и
      обрубленный текст, а по ячейкам выигрывает.  Замер без охраны: ячеек
      39 691, но слов на 11 046 меньше;
    * **рисунки.**  Свидетель не должен ссылаться `<img src="imgs/…">` на
      файл, которого нет ни наверху, ни в картинках его собственного прохода:
      битая ссылка видна читателю дырой.  Рамки блоков у проходов почти
      совпадают (расходится 0–5% ссылок), но именно «почти».

    Вырезки таблиц (`<!-- скан таблицы: … -->`) охраной НЕ считаются: их у
    свидетелей четырёх книг нет вовсе, а стоят они семь десятых всей прибавки
    (47 страниц, 5 149 ячеек).  Ссылка на невыгруженную вырезку переписывается
    в честную пометку (`drop_lost_scans`) и считается числом.

    Не заменённая страница отдаётся из книги прохода 1 БАЙТ В БАЙТ — со всеми
    сшивками и уровнями заголовков.  Если ни одна страница не заменена, свод
    даёт ровно тот же текст, что и до правки.
    """
    if not passes:
        return None
    names = [_pages_by_name(x) for x in passes]
    base_names = sorted(names[0])
    draft = layout.draft_of(passes[0])
    if not base_names or not os.path.exists(draft):
        return None
    book = open(draft, encoding="utf-8").read()

    text_of = [{n: open(f, encoding="utf-8").read() for n, f in m.items()}
               for m in names]
    base_texts = [text_of[0][n] for n in base_names]
    cuts, clean, blines = page_spans(base_texts, book)

    have = set(os.listdir(imgs_top)) if os.path.isdir(imgs_top) else set()
    for x in passes:
        d = os.path.join(x, "book", "imgs")
        if os.path.isdir(d):
            have |= set(os.listdir(d))

    pick = [0] * len(base_names)
    veto = collections.Counter()
    swapped = {}
    noscan = 0
    for i, name in enumerate(base_names):
        cands = []
        for k, t in enumerate(text_of):
            md = t.get(name)
            if md is None:
                continue
            cands.append((looped(md), -ladder(md), -cells_count(md), k))
        cands.sort()
        b = base_texts[i]
        floor = (KEEP_WORDS_LOOP if looped(b) else KEEP_WORDS) \
            * words_count(b)
        # Кандидаты перебираются по порядку, а не берётся один лучший: если
        # победитель отвергнут охраной, следующий за ним ещё может подойти, и
        # откат сразу к проходу 1 терял бы его молча.
        for cand in cands:
            k = cand[3]
            if k == 0:
                break
            if not clean[i]:
                veto["сшивка таблицы через разрыв страницы"] += 1
                break
            w = text_of[k][name]
            if words_count(w) < floor:
                veto["свидетель теряет слова"] += 1
                continue
            if any(os.path.basename(x) not in have for x in IMG_SRC.findall(w)):
                # Рисунок — это содержимое: битый `<img src>` виден читателю
                # дырой в html и ломает сверку epub по числу файлов.
                veto["рисунок, которого нет на диске"] += 1
                continue
            w, lost = drop_lost_scans(w, have)
            noscan += lost
            swapped[i] = w
            pick[i] = k
            break

    out = []
    for i in range(len(base_names)):
        if pick[i]:
            out.append(swapped[i].rstrip("\n") + "\n\n")
        else:
            out.append("".join(blines[cuts[i]:cuts[i + 1]]))
    text = "".join(out)

    # Свидетели строятся ПОСТРАНИЧНО из непринятых чтений.  Иначе страница,
    # взятая у прохода 2, сличалась бы сама с собой: её ячейки лежат в книге
    # прохода 2 по определению, пометка `≠` не встаёт никогда, и свод объявляет
    # надёжным то, что подтверждено одним чтением из трёх.
    wits, wit_src = [], []
    for slot in range(max(len(passes) - 1, 0)):
        parts, src = [], []
        for i, name in enumerate(base_names):
            other = [k for k in range(len(passes))
                     if k != pick[i] and name in text_of[k]]
            if not other:
                src.append(None)
                continue
            k = other[min(slot, len(other) - 1)]
            src.append(k)
            parts.append(text_of[k][name].rstrip("\n"))
        if parts:
            wits.append("\n\n".join(parts))
            wit_src.append(src)

    # «Было» считаем по книге прохода 1, а не по сумме его страниц: книгой
    # становилась именно она, и сравнивать надо с тем, что доходило до
    # читателя.  Разница невелика, но она есть — сшивка таблиц через разрыв
    # теряет ячейки (у «Справочника» 19 492 по страницам против 19 468 в
    # книге), и смешение двух знаменателей уже трижды портило выводы.
    # Зацикливание считаем по ТЕМ САМЫМ страницам, которые попали в книгу.
    # До сведения `assemble` звал `looping_pages(base)` — проход 1 целиком, —
    # и после Э2 это стало неправдой: книга собрана постранично.  Замер по
    # шести книгам: у прохода 1 зацикленных страниц 37, в собранной книге 18;
    # отчёт называл чужие 37 и молчал про свои 18.
    looped_pages = []
    # Пометка `⚠` — свойство ОДНОГО чтения: её ставит распознаватель по
    # вероятностям своих токенов.  Подменяя страницу, мы выбрасываем пометки
    # прохода 1 вместе с его текстом — поставить их на чужие слова нечем.
    # Молчать об этом нельзя: приёмка Э6 ловит ровно это («chugun: ⚠ 40 ->
    # 35» на стенде из 12 страниц).  Замер по шести книгам целиком: подменена
    # 211 страниц, на 38 из них пометок стало меньше (потеряно 65), на
    # остальных больше (прибавлено 402); по книгам ⚠ растёт везде, 2207 ->
    # 2544.  Число считается и печатается — решать читателю, а не нам.
    warn_lost = warn_got = warn_pages = 0
    for i, name in enumerate(base_names):
        hit = looping(text_of[pick[i]][name])
        if hit:
            looped_pages.append((name, hit))
        if pick[i]:
            a = text_of[0][name].count("⚠") if name in text_of[0] else 0
            b = text_of[pick[i]][name].count("⚠")
            if b < a:
                warn_lost += a - b
                warn_pages += 1
            else:
                warn_got += b - a

    note = dict(pages=len(base_names), veto=veto, noscan=noscan,
                looped=looped_pages,
                warn_lost=warn_lost, warn_got=warn_got, warn_pages=warn_pages,
                names=base_names, pick=pick, wit_src=wit_src,
                taken=collections.Counter(pick),
                cells_base=cells_count(book), cells_new=cells_count(text),
                words_base=words_count(book), words_new=words_count(text))
    return text, wits, note


def assemble(outdir):
    """Собрать готовую книгу из проходов, ничего не разрушая.

    Прежний свод начинался с `shutil.rmtree(dst)` и копирования основы — и это
    было опасно вдвойне.  Во-первых, 177 МБ страниц и картинок лежали на диске
    дважды.  Во-вторых, проверка показала настоящую беду: `--out`, указанный на
    каталог прохода, СНОСИЛ оплаченный проход, а свод после этого сличал основу
    сам с собой и печатал «помечено 0 (0%)» с кодом возврата 0.  Книга
    выглядела полностью сверенной именно там, где сверять стало нечем.

    Теперь сборка ничего не сносит и не копирует: она читает черновики
    проходов, а пишет ровно два файла наверху — книгу и слепок до сборки
    структуры.  Картинки ПЕРЕЕЗЖАЮТ из проходов наверх один раз; ссылки в
    тексте (`imgs/…`) от переезда не меняются.

    Слепок пишем здесь, а не в `restructure`: он обязан быть состоянием ДО
    расстановки заголовков, но ПОСЛЕ пометок свода, иначе отчёт сравнивает
    книгу с текстом, которого в ней никогда не было.
    """
    p = layout.Paths(outdir)
    if not p.new:
        raise SystemExit(f"нет проходов в {outdir}/passes — собирать не из чего")
    base, others = p.passes[0], p.passes[1:]

    draft = layout.draft_of(base)
    if not os.path.exists(draft):
        raise SystemExit(f"нет черновика основы: {draft}")

    chosen = choose_base(p.passes, p.imgs)
    if chosen is None:
        # Выбирать постранично не из чего — у основы нет `pages/*.md`.  Прежний
        # путь: книга прохода 1 целиком, свидетели — книги остальных.
        print("ВНИМАНИЕ: у основы нет постраничного вывода — основой взят "
              "проход 1 целиком, как до правки")
        remember_base(outdir,
                      {os.path.splitext(os.path.basename(f))[0]: 1
                       for f in sorted(glob.glob(os.path.join(base, "pages", "*.md")))},
                      note="постранично выбирать не из чего: вся книга — проход 1")
        text = open(draft, encoding="utf-8").read()
        wit = []
        for o in others:
            d = layout.draft_of(o)
            if os.path.exists(d):
                wit.append(open(d, encoding="utf-8").read())
            else:
                # Запасной путь: свидетеля не докачали книжным файлом, но
                # страницы есть.  Склейка грубее (таблицы через разрыв не
                # сшиты), однако молчаливо считать страницу сверенной нельзя.
                pg = sorted(glob.glob(os.path.join(o, "pages", "*.md")))
                if pg:
                    wit.append("\n\n".join(open(x, encoding="utf-8").read()
                                           for x in pg))
                else:
                    print(f"ВНИМАНИЕ: у прохода {os.path.relpath(o)} нет ни "
                          f"книги, ни страниц — свидетелем он не станет")
    else:
        text, wit, note = chosen
        taken = note["taken"]
        swapped = sum(v for k, v in taken.items() if k)
        print(f"основа собрана постранично: страниц {note['pages']}, "
              f"у прохода 1 взято {taken.get(0, 0)}, у свидетелей {swapped}"
              + "".join(f"; проход {k+1}: {v}"
                        for k, v in sorted(taken.items()) if k))
        print(f"непустых ячеек: в книге прохода 1 было {note['cells_base']}, "
              f"стало {note['cells_new']} "
              f"({note['cells_new'] - note['cells_base']:+d}); "
              f"слов {note['words_base']} -> {note['words_new']} "
              f"({note['words_new'] - note['words_base']:+d})")
        remember_base(outdir,
                      {os.path.splitext(name)[0]: k + 1
                       for name, k in zip(note["names"], note["pick"])},
                      note="постранично: не зациклено -> целее лестница -> "
                           "больше непустых ячеек -> проход 1 при равенстве")
        if note["warn_lost"] or note["warn_got"]:
            print(f"  пометок ⚠ прохода 1 не стало вместе с подменёнными "
                  f"страницами: {note['warn_lost']} (на {note['warn_pages']} "
                  f"стр.); пришло со свидетелей: {note['warn_got']}")
        for why, n in note["veto"].most_common():
            print(f"  свидетель отклонён, {why}: {n}")
        if note["noscan"]:
            print(f"ВНИМАНИЕ: таблиц, приехавших без вырезки скана "
                  f"(вырезка осталась на машине свидетеля): {note['noscan']}")

    if not wit:
        print("ВНИМАНИЕ: свидетелей нет — сверять было не с чем. "
              "Отсутствие пометок ≠ здесь не значит, что чтения сошлись.")
    else:
        print(f"свидетелей: {len(wit)}")

    text, prose, blind = mark_prose(text, wit)
    text, marked, total, empty = mark_cells(text, wit)
    # Улики зацикливания — по выбранным страницам (их знает `choose_base`).
    # Прежним путём (вся книга из прохода 1) считаем по проходу 1: там это и
    # есть выбранные страницы.
    looped = (chosen[2].get("looped") if chosen else None)
    if looped is None:
        looped = looping_pages(base)

    os.makedirs(os.path.dirname(p.book), exist_ok=True)
    with open(p.book, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(p.snapshot, "w", encoding="utf-8") as fh:
        fh.write(text)

    # Картинки переезжают, а не копируются: книга ими владеет.  Если наверху
    # уже есть свои — не трогаем ничего, повторная сборка не должна зависеть
    # от того, остались ли картинки в проходе.
    src_imgs = os.path.join(base, "book", "imgs")
    if os.path.isdir(src_imgs):
        if not os.path.isdir(p.imgs):
            shutil.move(src_imgs, p.imgs)
            print(f"картинки переехали наверх: {len(os.listdir(p.imgs))} шт.")
        else:
            # Наверху уже что-то есть.  Молча пропускать переезд нельзя: набор
            # выживших вырезок у каждого прохода СВОЙ, и книга, собранная из
            # нового прохода поверх старых картинок, ссылается на файлы,
            # которых наверху нет.  Проверка нашла ровно это: повторный
            # `books ocr` в тот же каталог штатно давал битые ссылки.
            add = [n for n in os.listdir(src_imgs)
                   if not os.path.exists(os.path.join(p.imgs, n))]
            for n in add:
                shutil.move(os.path.join(src_imgs, n),
                            os.path.join(p.imgs, n))
            print(f"картинки наверху уже были; добавлено недостающих: "
                  f"{len(add)}")
    # Страница, взятая у свидетеля, ссылается на вырезки СВОЕГО прохода.  Рамки
    # блоков у проходов почти совпадают, и почти все ссылки ведут на уже
    # переехавшие файлы, но именно «почти».  Выбор страниц уже отказался от
    # свидетеля, у которого картинки нет нигде; здесь переносим наверх то, что
    # нашлось у него самого.
    want = {os.path.basename(x) for x in
            IMG_SRC.findall(text) + TBL_SCAN.findall(text)}
    if os.path.isdir(p.imgs):
        want -= set(os.listdir(p.imgs))
    moved = 0
    for o in others:
        d = os.path.join(o, "book", "imgs")
        if not want or not os.path.isdir(d):
            continue
        os.makedirs(p.imgs, exist_ok=True)
        for n in sorted(want & set(os.listdir(d))):
            shutil.move(os.path.join(d, n), os.path.join(p.imgs, n))
            want.discard(n)
            moved += 1
    if moved:
        print(f"картинок добрано у свидетелей: {moved}")
    lost = [m.group(1) for m in re.finditer(r'src="(imgs/[^"]+)"', text)
            if not os.path.exists(os.path.join(p.outdir, m.group(1)))]
    if lost:
        print(f"ВНИМАНИЕ: текст ссылается на {len(lost)} картинок, которых "
              f"наверху нет (первая: {lost[0]})")

    pages = len(glob.glob(os.path.join(base, "pages", "*.md")))
    thin = [os.path.relpath(o) for o in others
            if len(glob.glob(os.path.join(o, "pages", "*.md"))) < pages]
    print(f"ячеек в таблицах {total} (из них пустых {empty}), помечено "
          f"неустойчивыми {marked} ({marked/max(total,1):.0%})")
    if looped:
        worst = max(looped, key=lambda x: x[1]["chars"])
        print(f"ВНИМАНИЕ: страниц основы с признаками зацикливания: "
              f"{len(looped)} (худшая {worst[0]}: {worst[1]['kind']}, "
              f"{worst[1]['chars']}); их содержимое в книге — не книга")
    print(f"чисел в прозе помечено {prose}; абзацев с числами, не сошедшихся "
          f"ни с одним свидетелем и потому не сверенных: {blind}")
    if thin:
        print(f"ВНИМАНИЕ: у свидетелей меньше страниц, чем у основы "
              f"({pages}): {', '.join(thin)}")
    print(f"книга собрана: {p.book}")
    return 0
